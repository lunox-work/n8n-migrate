#!/usr/bin/env node
// Builds the runner's two shippable files from skills/n8n-migrate/runtime/src:
//   dist/runner-core.mjs  every core module, browser-safe (no node: imports)
//   dist/runner.mjs       the Node CLI, importing ./runner-core.mjs
//   dist/luxon.mjs        a copy of the vendored Luxon the core imports
//   dist/driver.mjs       the task driver (Node), copied from src as is
//   dist/hook.mjs         the Claude Code hooks (Node), copied from src as is
//   dist/store.mjs        the task driver's record store (Node), copied from src as is
//   dist/dispatch.mjs     the repo-root hook dispatcher (convert.mjs writes it as n8m-hook.mjs)
//   dist/pgclient.mjs     the Postgres client host (Node), copied from src as is; loads runtime/vendor/pg
//   dist/artifact-runtime.js  Luxon + core + artifact driver as one classic script for the page
//
//   node scripts/build-runtime.mjs [--check]
//
// A tiny concatenating bundler with no dependencies: each module becomes a function
// scope that returns its exports; `import {a} from "./m.mjs"` becomes `const {a} = __m;`
// in dependency order. It understands only the import/export forms the runtime uses.
// --check exits 1 when dist differs from what the sources produce.

import { readFileSync, writeFileSync, existsSync, mkdirSync } from "node:fs";
import { dirname, join, resolve, relative, basename } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const RT = join(ROOT, "skills/n8n-migrate/runtime");
const SRC = join(RT, "src");
const DIST = join(RT, "dist");
const VENDOR_LUXON = join(RT, "vendor/luxon.mjs");

const IMPORT_RE = /^import\s+\{([^}]*)\}\s+from\s+"([^"]+)";\s*$/;
const REEXPORT_RE = /^export\s+\{([^}]*)\}\s+from\s+"([^"]+)";\s*$/;
const LOCAL_EXPORT_RE = /^export\s+\{([^}]*)\};\s*$/;
const DECL_EXPORT_RE = /^export\s+((?:async\s+)?function\*?|class|const|let)\s+([A-Za-z_$][\w$]*)/;

const names = (list) => list.split(",").map((s) => s.trim()).filter(Boolean);

function parseModule(file) {
  const lines = readFileSync(file, "utf8").split("\n");
  const imports = [];
  const exports = [];
  const reexports = [];
  const body = [];
  for (const line of lines) {
    let m;
    if ((m = IMPORT_RE.exec(line))) imports.push({ names: names(m[1]), from: m[2] });
    else if ((m = REEXPORT_RE.exec(line))) reexports.push({ names: names(m[1]), from: m[2] });
    else if ((m = LOCAL_EXPORT_RE.exec(line))) exports.push(...names(m[1]));
    else if ((m = DECL_EXPORT_RE.exec(line))) {
      exports.push(m[2]);
      body.push(line.replace(/^export\s+/, ""));
    } else {
      if (/^\s*(import|export)\s/.test(line)) throw new Error(`${relative(ROOT, file)}: unsupported module syntax: ${line}`);
      if (/\bfrom\s+"node:|require\(\s*"node:/.test(line)) throw new Error(`${relative(ROOT, file)}: node: import in the core`);
      body.push(line);
    }
  }
  for (const n of [...exports, ...reexports.flatMap((r) => r.names)]) if (/\sas\s/.test(n)) throw new Error(`${relative(ROOT, file)}: "as" renames are not supported`);
  return { file, imports, exports, reexports, body };
}

function bundleCore() {
  const order = [];
  const mods = new Map();
  const luxonNames = new Set();
  const visit = (file, stack = []) => {
    if (mods.has(file)) return;
    if (stack.includes(file)) throw new Error(`import cycle: ${[...stack, file].map((f) => basename(f)).join(" -> ")}`);
    const mod = parseModule(file);
    mods.set(file, mod);
    for (const imp of [...mod.imports, ...mod.reexports]) {
      const target = resolve(dirname(file), imp.from);
      if (target === VENDOR_LUXON) {
        imp.names.forEach((n) => luxonNames.add(n));
        imp.luxon = true;
        continue;
      }
      if (!imp.from.startsWith(".")) throw new Error(`${basename(file)}: only relative imports are bundled (${imp.from})`);
      imp.target = target;
      visit(target, [...stack, file]);
    }
    order.push(file);
  };
  const entry = join(SRC, "index.mjs");
  visit(entry);
  const id = (file) => "__m_" + relative(SRC, file).replace(/\W/g, "_");
  const out = [];
  out.push("// n8n-migrate runner core: GENERATED by scripts/build-runtime.mjs from runtime/src. Do not edit.");
  out.push("// Browser-safe: no node: imports. Imports Luxon from ./luxon.mjs (vendored, MIT).");
  out.push(`import { ${[...luxonNames].sort().join(", ")} } from "./luxon.mjs";`);
  let entryExports = [];
  for (const file of order) {
    const mod = mods.get(file);
    if (file === entry) {
      for (const r of mod.reexports) entryExports.push(...r.names.map((n) => ({ name: n, from: r.target })));
      continue;
    }
    out.push("", `// ---- ${relative(RT, file)} ----`, `const ${id(file)} = (() => {`);
    for (const imp of mod.imports) if (!imp.luxon) out.push(`const { ${imp.names.join(", ")} } = ${id(imp.target)};`);
    out.push(...mod.body);
    out.push(`return { ${mod.exports.join(", ")} };`, "})();");
  }
  const seen = new Set();
  const decls = [];
  for (const e of entryExports) {
    if (seen.has(e.name)) throw new Error(`duplicate export ${e.name}`);
    seen.add(e.name);
    decls.push(`const ${e.name} = ${id(e.from)}.${e.name};`);
  }
  out.push("", ...decls, `export { ${entryExports.map((e) => e.name).join(", ")} };`, "");
  return out.join("\n");
}

function bundleCli() {
  const src = readFileSync(join(SRC, "cli.mjs"), "utf8");
  if (!src.includes('from "./index.mjs";')) throw new Error("cli.mjs must import ./index.mjs");
  const lines = src.split("\n");
  const shebang = lines[0].startsWith("#!") ? lines.shift() + "\n" : "";
  return shebang + "// GENERATED by scripts/build-runtime.mjs from runtime/src/cli.mjs. Do not edit.\n" + lines.join("\n").replaceAll('from "./index.mjs";', 'from "./runner-core.mjs";');
}

// Node-side files that import nothing from the core: copied with a GENERATED line.
export const NODE_FILES = ["cli.mjs", "driver.mjs", "hook.mjs", "store.mjs", "dispatch.mjs", "pgclient.mjs"];
function copied(name) {
  const src = readFileSync(join(SRC, name), "utf8");
  for (const m of src.matchAll(/^import\s.*?from\s+"(\.[^"]+)";/gm)) if (!["./driver.mjs", "./store.mjs"].includes(m[1])) throw new Error(`${name}: may import only ./driver.mjs and ./store.mjs, not ${m[1]}`);
  const lines = src.split("\n");
  const shebang = lines[0].startsWith("#!") ? lines.shift() + "\n" : "";
  return shebang + `// GENERATED by scripts/build-runtime.mjs from runtime/src/${name}. Do not edit.\n` + lines.join("\n");
}

// The artifact page's one classic script: Luxon, the core and the artifact driver, each in a
// function scope, published as globalThis.N8M = {core, artifact}. The page inlines it, so it
// loads nothing from a CDN (references/artifact.html; convert.mjs fills the template).
const MODULE_EXPORT_RE = /^export\s+\{([^}]*)\};\s*$/m;
function asScope(name, text, importLine) {
  const m = MODULE_EXPORT_RE.exec(text);
  if (!m) throw new Error(`${name}: no export list`);
  let body = text.replace(MODULE_EXPORT_RE, `return { ${m[1].trim()} };`);
  if (importLine) body = body.replace(importLine.re, importLine.to);
  if (/^\s*(import|export)\s/m.test(body)) throw new Error(`${name}: module syntax left after wrapping`);
  return body;
}
function bundleArtifact(core) {
  const luxon = readFileSync(VENDOR_LUXON, "utf8");
  const drv = parseModule(join(SRC, "artifact-driver.mjs"));
  if (drv.imports.length || drv.reexports.length) throw new Error("artifact-driver.mjs must import nothing (the core is passed in)");
  const out = [
    "// n8n-migrate artifact runtime: GENERATED by scripts/build-runtime.mjs. Do not edit.",
    "// Luxon (vendored, MIT) + runner core + artifact driver, as one classic script: globalThis.N8M.",
    "(function () {",
    '"use strict";',
    "const __luxon = (() => {",
    asScope("luxon.mjs", luxon),
    "})();",
    "const __core = (() => {",
    asScope("runner-core.mjs", core, { re: /^import\s+\{([^}]*)\}\s+from\s+"\.\/luxon\.mjs";\s*$/m, to: "const {$1} = __luxon;" }),
    "})();",
    "const __artifact = (() => {",
    ...drv.body,
    `return { ${drv.exports.join(", ")} };`,
    "})();",
    "globalThis.N8M = Object.freeze({ core: __core, artifact: __artifact });",
    "})();",
    "",
  ].join("\n");
  if (/<\/script/i.test(out)) throw new Error("the artifact runtime contains </script, which would end the inline script");
  return out;
}

export function buildRuntime() {
  const core = bundleCore();
  return {
    "runner-core.mjs": core,
    "artifact-runtime.js": bundleArtifact(core),
    "runner.mjs": bundleCli(),
    "luxon.mjs": readFileSync(VENDOR_LUXON, "utf8"),
    "driver.mjs": copied("driver.mjs"),
    "hook.mjs": copied("hook.mjs"),
    "store.mjs": copied("store.mjs"),
    "dispatch.mjs": copied("dispatch.mjs"),
    "pgclient.mjs": copied("pgclient.mjs"),
  };
}

const isMain = process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const check = process.argv.includes("--check");
  const files = buildRuntime();
  let stale = [];
  if (!check) mkdirSync(DIST, { recursive: true });
  for (const [name, content] of Object.entries(files)) {
    const path = join(DIST, name);
    const current = existsSync(path) ? readFileSync(path, "utf8") : null;
    if (current === content) continue;
    if (check) stale.push(name);
    else writeFileSync(path, content);
  }
  if (check && stale.length) {
    console.error(`runtime/dist is stale: ${stale.join(", ")}. Run node scripts/build-runtime.mjs`);
    process.exit(1);
  }
  for (const [name, content] of Object.entries(files)) console.log(`${check ? "ok" : "wrote"} dist/${name} ${(Buffer.byteLength(content) / 1024).toFixed(1)} KB`);
}
