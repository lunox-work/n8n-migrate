export function canonical(v) {
  if (Array.isArray(v)) return `[${v.map(canonical).join(",")}]`;
  if (v && typeof v === "object")
    return `{${Object.keys(v)
      .sort()
      .map((k) => `${JSON.stringify(k)}:${canonical(v[k])}`)
      .join(",")}}`;
  return JSON.stringify(v);
}

// Strips control and bidi-override characters from untrusted text before it
// reaches a terminal.
const clean = (s) => String(s).replace(/[\u0000-\u001f\u007f-\u009f‪-‮⁦-⁩]/g, " ");

export function formatDuration(sec) {
  if (sec == null) return "?";
  const trim = (x) => String(round(x, 2));
  if (sec < 60) return `${trim(sec)} s`;
  if (sec < 3600) return `${trim(sec / 60)} min`;
  if (sec < 86400) return `${trim(sec / 3600)} h`;
  return `${trim(sec / 86400)} d`;
}

// ---------- input ----------

// Returns [{id, name, wf}] for every workflow in one parsed JSON value, or
// null when the value holds none.
export function unwrap(data, label) {
  if (Array.isArray(data)) {
    const out = [];
    data.forEach((x, i) => out.push(...(unwrap(x, `${label}#${i}`) || [])));
    return out.length ? out : null;
  }
  if (!isObj(data)) return null;
  if (Array.isArray(data.data)) return unwrap(data.data, label);
  const t = data.workflow;
  if (isObj(t) && isObj(t.workflow) && Array.isArray(t.workflow.nodes)) {
    return [{ id: String(t.id ?? t.workflow.id ?? label), name: String(t.name ?? t.workflow.name ?? label), wf: t.workflow }];
  }
  if (Array.isArray(data.nodes)) return [{ id: String(data.id ?? label), name: String(data.name ?? label), wf: data }];
  return null;
}

function listJsonFiles(dir) {
  const out = [];
  for (const e of readdirSync(dir).sort()) {
    if (e.startsWith(".") || e === "node_modules") continue;
    const p = join(dir, e);
    const st = statSync(p);
    if (st.isDirectory()) out.push(...listJsonFiles(p));
    else if (st.isFile() && e.endsWith(".json")) out.push(p);
  }
  return out;
}

// Loads the CLI input. A single unreadable file or stdin is fatal (exit 2); in
// a folder, unreadable files are recorded and skipped.
export function loadInput(arg, readStdin = () => readFileSync(0, "utf8")) {
  const items = [];
  const errors = [];
  const add = (data, label, file) => {
    const ws = unwrap(data, label);
    if (!ws) return false;
    for (const w of ws) items.push({ ...w, file });
    return true;
  };
  if (arg === "-") {
    let data;
    try {
      data = JSON.parse(readStdin());
    } catch (e) {
      return { fatal: `stdin is not JSON: ${e.message}` };
    }
    if (!add(data, "stdin", "-")) return { fatal: "stdin holds no n8n workflow" };
    return { items, errors };
  }
  let st;
  try {
    st = statSync(arg);
  } catch {
    return { fatal: `cannot read ${arg}` };
  }
  if (st.isDirectory()) {
    for (const f of listJsonFiles(arg)) {
      const rel = relative(arg, f);
      let data;
      try {
        data = JSON.parse(readFileSync(f, "utf8"));
      } catch (e) {
        errors.push({ file: rel, error: `not JSON: ${e.message}` });
        continue;
      }
      if (!add(data, rel.replace(/\.json$/, ""), rel)) errors.push({ file: rel, error: "no n8n workflow in this file" });
    }
    if (!items.length) return { fatal: `no n8n workflow under ${arg}` };
    return { items, errors };
  }
  let data;
  try {
    data = JSON.parse(readFileSync(arg, "utf8"));
  } catch (e) {
    return { fatal: `${arg} is not JSON: ${e.message}` };
  }
  if (!add(data, basename(arg).replace(/\.json$/, ""), basename(arg))) return { fatal: `${arg} holds no n8n workflow` };
  return { items, errors };
}

// ---------- catalogue lookup ----------

// A mapping value may be a rule object (see mappings.json $doc):
// {param, values, other, default}. Returns undefined when undetermined.
function resolveRule(v, params) {
  if (!isObj(v) || !("param" in v)) return v;
  let val;
  for (const p of [].concat(v.param)) {
    if (params[p] !== undefined) {
      val = params[p];
      break;
    }
  }
  if (val === undefined) return v.default;
  if (isExpr(val)) return undefined;
  const hit = v.values?.[String(val)];
  return hit !== undefined ? hit : v.other;
}

// Everything the analyzer needs about one node, from nodes.json and the
// node's own parameters. Resource and operation resolve the way n8n does:
// the parameter if set, else the package default for that version.
function describeNode(catalogue, node) {
  const type = String(node.type ?? "");
  const params = isObj(node.parameters) ? node.parameters : {};
  const typeVersion = typeof node.typeVersion === "number" ? node.typeVersion : Number(node.typeVersion ?? 1);
  const d = {
    node,
    name: String(node.name ?? ""),
    type,
    typeVersion,
    params,
    disabled: node.disabled === true,
    status: "mapped",
    entry: catalogue[type],
    baseType: type,
    role: null,
    wakeup: undefined,
    kind: null,
    levers: [],
    connector: null,
    secrets: undefined,
    effect: undefined,
    effectBy: null,
    reason: null,
    notes: null,
    flags: [],
    resource: null,
    operation: null,
    opKey: null,
    issues: [],
    isTrigger: false,
  };
  const e = d.entry;
  if (!e) {
    d.status = "not-in-catalogue";
    d.issues.push("not-in-catalogue");
    return d;
  }
  if (e.toolVariantOf) d.baseType = e.toolVariantOf;
  if (e.mapping === "unmapped") {
    d.status = "unmapped";
    d.isTrigger = !!e.trigger;
    return d;
  }
  const m = e.mapping;
  if (e.versions && !e.versions.includes(typeVersion)) d.issues.push("unknown-version");
  const opParam = m.operationParam || "operation";
  if (e.ops) {
    const g = e.ops.find((x) => x.versions.includes(typeVersion)) || e.ops.at(-1);
    if (g.resources) {
      const res = params.resource ?? g.resourceDefault;
      d.resource = res == null ? null : String(res);
      if (isExpr(res)) d.issues.push("expression-operation");
      else {
        const rg = g.resources[res];
        const op = params[opParam] ?? rg?.default;
        d.operation = op == null ? null : String(op);
        if (isExpr(op)) d.issues.push("expression-operation");
        else {
          d.opKey = `${res}:${op}`;
          if (!rg || !rg.operations.includes(String(op))) d.issues.push("unknown-operation");
        }
      }
    } else {
      const op = params[opParam] ?? g.default;
      d.operation = op == null ? null : String(op);
      if (isExpr(op)) d.issues.push("expression-operation");
      else {
        d.opKey = String(op);
        if (!g.operations.includes(d.opKey)) d.issues.push("unknown-operation");
      }
    }
  } else if (e.operations && params[opParam] !== undefined && !isExpr(params[opParam])) {
    d.operation = String(params[opParam]);
    d.opKey = d.operation;
  }
  const om = (d.opKey && e.operations?.[d.opKey]) || {};
  const pick = (k) => (om[k] !== undefined ? om[k] : m[k]);
  d.role = resolveRule(m.role, params) ?? "step";
  d.wakeup = resolveRule(m.wakeup, params);
  d.kind = pick("kind") ?? null;
  d.levers = [...(om.levers ?? m.levers ?? [])].sort();
  d.connector = pick("connector") ?? null;
  d.secrets = resolveRule(pick("secrets"), params);
  const effect = om.effect !== undefined ? om.effect : m.effect;
  d.effect = resolveRule(effect, params);
  if (d.effect !== undefined) d.effectBy = om.effect !== undefined ? om.effectBy || "hand" : "hand";
  d.reason = pick("reason") ?? null;
  d.notes = pick("notes") ?? null;
  d.flags = (m.flags || []).map((f) => resolveRule(f, params)).filter(Boolean);
  d.isTrigger = d.role === "trigger" || (d.role === "n8n-internal" && !!e.trigger);
  return d;
}

// ---------- parameter parsing: code, SQL, strings ----------

function allStrings(v, out = []) {
  if (typeof v === "string") out.push(v);
  else if (Array.isArray(v)) v.forEach((x) => allStrings(x, out));
  else if (isObj(v)) Object.values(v).forEach((x) => allStrings(x, out));
  return out;
}

// A Code node's effect is "none" when its source shows no way out of the
// process: no HTTP helper, fetch, require/import, or static data. Anything
// else leaves the effect unknown.
const CODE_EXIT = /helpers\s*\.\s*(?:httpRequest|request)|\bfetch\s*\(|\brequire\s*\(|\bimport\s*\(|\$http|axios|getWorkflowStaticData|\bsubprocess\b|\bos\.system|\bopen\s*\(/;
function codeEffect(params) {
  return CODE_EXIT.test(allStrings(params).join("\n")) ? undefined : "none";
}

// Effect of a SQL text by its statement verbs. Expression parts ({{ }}) are
// blanked; a statement whose verb sits inside an expression is undetermined.
export function sqlEffect(q) {
  if (typeof q !== "string") return undefined;
  let s = q.startsWith("=") ? q.slice(1) : q;
  s = s.replace(/\{\{[\s\S]*?\}\}/g, " __EXPR__ ");
  s = s.replace(/--[^\n]*/g, " ").replace(/\/\*[\s\S]*?\*\//g, " ");
  const stmts = s
    .split(";")
    .map((x) => x.trim())
    .filter(Boolean);
  if (!stmts.length) return undefined;
  const READ = new Set(["SELECT", "SHOW", "EXPLAIN", "DESCRIBE", "DESC", "VALUES", "TABLE"]);
  const WRITE = new Set(["INSERT", "UPDATE", "DELETE", "MERGE", "UPSERT", "REPLACE", "CREATE", "DROP", "ALTER", "TRUNCATE", "GRANT", "REVOKE", "COPY", "VACUUM", "COMMENT", "RENAME", "LOCK"]);
  let result = "read";
  for (const st of stmts) {
    const verb = (st.replace(/^[\s(]+/, "").match(/^[A-Za-z_]+/) || [""])[0].toUpperCase();
    if (WRITE.has(verb)) return "write";
    if (verb === "WITH") {
      if (/\b(?:insert|update|delete|merge)\b/i.test(st)) return "write";
      continue;
    }
    if (verb === "SELECT" && /\binto\s+(?!@)[a-z_"`[]/i.test(st) && !/\binsert\s+into\b/i.test(st)) return "write";
    if (!READ.has(verb)) result = undefined;
  }
  return result;
}

