const USAGE = "usage: analyze.mjs <path|-> [--json] [--out file] [--answers file] [--now ISO] [--nodes path] [--capabilities path] [--hosts path]";

function parseArgs(argv) {
  const a = { input: null, json: false, out: null, nodes: join(REFS, "nodes.json"), capabilities: join(REFS, "capabilities.json"), hosts: join(REFS, "http-hosts.json"), answers: null, now: null };
  for (let i = 0; i < argv.length; i++) {
    const x = argv[i];
    const val = () => {
      if (i + 1 >= argv.length) throw new Error(`${x} needs a value`);
      return argv[++i];
    };
    if (x === "--json") a.json = true;
    else if (x === "--out") a.out = resolve(val());
    else if (x === "--nodes") a.nodes = resolve(val());
    else if (x === "--capabilities") a.capabilities = resolve(val());
    else if (x === "--hosts") a.hosts = resolve(val());
    else if (x === "--answers") a.answers = resolve(val());
    else if (x === "--now") a.now = val();
    else if (x === "-h" || x === "--help") a.help = true;
    else if (x.startsWith("--")) throw new Error(`unknown option ${x}`);
    else if (a.input === null) a.input = x === "-" ? "-" : resolve(x);
    else throw new Error(`unexpected argument ${x}`);
  }
  return a;
}

function main() {
  let a;
  try {
    a = parseArgs(process.argv.slice(2));
  } catch (e) {
    console.error(`${e.message}\n${USAGE}`);
    process.exit(2);
  }
  if (a.help) {
    console.log(USAGE);
    return;
  }
  if (!a.input) {
    console.error(USAGE);
    process.exit(2);
  }
  const readJson = (p, what) => {
    try {
      return JSON.parse(readFileSync(p, "utf8"));
    } catch (e) {
      console.error(`cannot read ${what} ${p}: ${e.message}`);
      process.exit(2);
    }
  };
  const nodes = readJson(a.nodes, "node catalogue");
  const capabilities = readJson(a.capabilities, "capabilities");
  const hosts = readJson(a.hosts, "host rules");
  const answers = a.answers ? readJson(a.answers, "answers") : {};
  let now = Date.now();
  if (a.now) {
    now = Date.parse(a.now);
    if (Number.isNaN(now)) {
      console.error(`--now: not a date: ${a.now}`);
      process.exit(2);
    }
  }
  const input = loadInput(a.input);
  if (input.fatal) {
    console.error(input.fatal);
    process.exit(2);
  }
  const report = analyze(input.items, { nodes, capabilities, hosts, answers, now, inputErrors: input.errors });
  const text = a.json ? JSON.stringify(report, null, 2) + "\n" : renderText(report, !a.out && process.stdout.isTTY);
  if (a.out) {
    writeFileSync(a.out, text);
    console.error(`wrote ${a.out} (${report.summary.workflows} workflows)`);
  } else process.stdout.write(text);
}

