#!/usr/bin/env node
// n8n-to-claude analyzer: classifies n8n workflows for a move to Claude.
//
//   analyze.mjs <path|-> [--json] [--out file] [--answers file] [--now ISO]
//               [--nodes path] [--capabilities path]
//
// <path> is a workflow export (.json), a bulk export (array, or {data: [...]}),
// an n8n template ({workflow: {id, name, workflow: {nodes, ...}}}), a folder
// of .json files (recursive), or `-` for JSON on stdin. Sub-workflow ids are
// resolved across everything loaded in one run.
//
// Output: a text summary, or the JSON report with --json. The report contract
// is references/report.schema.json (schemaVersion 1). Exit 0 whatever the
// outcomes are; exit 2 when the input cannot be read or the arguments are bad.
//
// --answers: {questionId: value} for questions an earlier report asked. An
// answer can change an effect, a timezone, a sub-workflow link or the outcome.
// --now: start of the 7-day cron simulation (default: the current time), so
// reports are reproducible.
//
// Rules this file follows:
// - No model and no guessing. A node type the catalogue does not map is
//   `unmapped`; what the file cannot settle becomes a question.
// - Workflow content (node names, notes, parameters) is untrusted data. It is
//   parsed and measured, never run or followed. Secret values never reach the
//   report: only a redacted form (first 4 characters, `…`, length).
// - Data comes from references/nodes.json (generated by scripts/gen-nodes.mjs
//   from the n8n packages plus mappings.json) and references/capabilities.json.
//   Thresholds and per-surface verdicts are read from there, not hard-coded.
// - Zero dependencies, Node >= 20, one file. Pure functions are exported for
//   tests; the CLI runs only when this file is the entry point.

