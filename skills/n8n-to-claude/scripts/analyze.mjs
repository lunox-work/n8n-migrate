function finalizeRequires(W, ctx) {
  // n8n's in-process chat memory needs a store only outside a chat: in a skill
  // the Claude conversation is the memory.
  if (W.wakeup.kind === "chat") W.req.delete("state\u0000chat-memory");
  for (const r of W.req.values()) {
    if (r.kind === "connector") {
      const { surfaces, confirmed, noTool } = connectorSurfaces(ctx.capabilities, r.name, r.ops);
      r.surfaces = surfaces;
      r.confirmed = confirmed;
      r.noTool = noTool;
      // A connector that stands in for a node with its own REST API keeps
      // that path as an alternative: the n8n credential, as a stored secret.
      const alt = own(own(ctx.capabilities.connectors, r.name), "alternative");
      if (alt) r.alternative = { kind: "http", secrets: [...(r.creds || [])].sort(), surfaces: surfacesFrom(ctx.capabilities.requirements?.[alt.requirement]), note: txt(alt.note) };
    }
  }
  const needsServer = [...W.req.values()].filter((r) => r.kind !== "bundled-server" && r.surfaces?.localTask === "needs:bundled-server");
  if (needsServer.length) {
    const nodes = new Set(needsServer.flatMap((r) => [...r.nodes]));
    const r = addReq(W, "bundled-server", "local MCP server", null, { surfaces: surfacesFrom(ctx.capabilities.requirements?.["bundled-server"]) });
    for (const n of nodes) r.nodes.add(n);
  }
}

function nodeSort(W) {
  return (a, b) => {
    const ia = W.order.indexOf(a);
    const ib = W.order.indexOf(b);
    return (ia < 0 ? 1e9 : ia) - (ib < 0 ? 1e9 : ib) || a.localeCompare(b);
  };
}

function stepOf(W, d) {
  const role = d.status === "mapped" ? d.role : "unknown";
  let effect = d.effect ?? null;
  if (effect === null && (role === "step" || role === "subnode" || role === "unknown")) effect = "unknown";
  return {
    node: d.name,
    type: d.type,
    typeVersion: d.typeVersion,
    role,
    branch: publicBranch(W.branch.get(d.name)),
    resource: d.resource,
    operation: d.operation,
    kind: d.kind,
    effect,
    effectBy: effect === "unknown" ? null : d.effectBy,
    levers: d.levers,
    mapping: d.status !== "mapped" ? "unmapped" : d.effectBy === "name" ? "name" : "hand",
    issues: d.issues,
  };
}

function reportOf(W, ctx) {
  const sortNodes = (xs) => [...xs].sort(nodeSort(W));
  const requires = [...W.req.values()]
    .map((r) => {
      const o = { kind: r.kind, name: r.name, nodes: sortNodes(r.nodes), surfaces: r.surfaces ?? surfacesFrom(null) };
      if (r.note) o.note = r.note;
      if (r.kind === "connector") {
        o.operations = uniq(r.ops.map((x) => `${shortType(x.type)} ${x.op}`)).sort();
        o.confirmed = r.confirmed;
        if (r.noTool?.length) o.noTool = r.noTool;
        if (r.alternative) o.alternative = r.alternative;
      }
      return o;
    })
    .sort((a, b) => byOrder(REQ_ORDER)(a.kind, b.kind) || a.name.localeCompare(b.name));
  const blockers = [...W.blockers.values()]
    .map((b) => ({ kind: b.kind, reason: b.reason, nodes: sortNodes(b.nodes) }))
    .sort((a, b) => byOrder(BLOCKER_ORDER)(a.kind, b.kind) || a.reason.localeCompare(b.reason));
  const shared = [...W.sharedState.values()]
    .map((s) => {
      const o = { kind: s.kind, name: s.name, nodes: sortNodes(s.nodes), sharedWith: [] };
      if (["data-table", "vector-memory"].includes(s.kind)) o.sharedWith = (ctx.sharedIndex.get(`${s.kind}\u0000${s.key}`) || []).filter((id) => id !== W.id).sort(); // not input order: n8n's --separate export names files by id
      return o;
    })
    .sort((a, b) => a.kind.localeCompare(b.kind) || a.name.localeCompare(b.name));
  return {
    id: W.id,
    name: W.name,
    file: W.file,
    sourceHash: createHash("sha256").update(canonical(W.wf)).digest("hex"),
    wakeup: W.wakeup,
    body: W.body,
    outcome: W.outcome,
    ...(W.setupOnly ? { setupOnly: true, setupOnlyReason: W.setupOnly.reason } : {}),
    calledBy: [...W.calledBy].sort(),
    calls: W.callInfo.map((c) => ({ node: c.node, status: c.status, target: c.target })),
    requires,
    questions: W.questions.map(({ value, ...q }) => q).sort((a, b) => a.id.localeCompare(b.id)),
    blockers,
    credentials: W.credentials,
    inlineSecrets: W.inlineSecrets,
    schedule: W.schedule,
    sharedState: shared,
    disabled: W.disabled,
    steps: W.order
      .map((n) => W.infos.get(n))
      .filter((d) => !d.disabled && d.role !== "annotation")
      .map((d) => stepOf(W, d)),
    unmapped: W.unmapped,
    levers: [...W.levers].sort(),
  };
}

function thresholdsFrom(caps) {
  const t = {};
  for (const [k, v] of Object.entries(caps.thresholds || {})) t[k] = isObj(v) ? v.value : v;
  for (const k of ["cloudMinIntervalSec", "localMinIntervalSec"]) if (typeof t[k] !== "number") throw new Error(`capabilities.json: thresholds.${k} is missing`);
  return t;
}

// Analyses every loaded workflow together and returns the report.
export function analyze(items, { nodes, capabilities, hosts = { model: [], read: [] }, answers = {}, now = Date.now(), inputErrors = [] }) {
  const ctx = {
    catalogue: nodes.nodes,
    capabilities,
    hosts,
    thresholds: thresholdsFrom(capabilities),
    answers: isObj(answers) ? answers : {},
    used: new Set(),
    answerErrors: [],
    now,
    items: [],
    byId: new Map(),
    pseudo: [],
    sharedIndex: new Map(),
  };
  // Ids must be unique within a run; a repeated id gets a ~2, ~3 suffix.
  for (const it of items) {
    let id = it.id;
    for (let i = 2; ctx.byId.has(id); i++) id = `${it.id}~${i}`;
    const item = { ...it, id };
    ctx.items.push(item);
    ctx.byId.set(id, null);
  }
  const Ws = ctx.items.map((it) => analyzeLocal(it, ctx));
  Ws.forEach((W) => ctx.byId.set(W.id, W));
  for (const W of Ws) {
    W.wakeup = computeWakeup(W);
    W.schedule = computeSchedule(W, ctx);
  }
  for (const W of Ws) resolveCalls(W, ctx);
  for (const W of Ws) askWrites(W, ctx);
  for (const W of Ws) askSites(W, ctx);
  for (const W of Ws) askHosts(W, ctx);
  for (const W of Ws) askDatabases(W, ctx);
  const all = [...Ws, ...ctx.pseudo];
  all.forEach(snapshotOwn);
  all.forEach((W) => propagate(W));
  for (const W of Ws) {
    W.body = computeBody(W);
    finalizeRequires(W, ctx);
    W.setupOnly = setupOnly(W);
    const naa = notAnAutomation(W);
    if (naa) {
      addBlocker(W, "not-an-automation", naa.reason);
      for (const n of naa.nodes) W.blockers.get(`not-an-automation\u0000${naa.reason}`).nodes.add(n);
    }
  }
  for (const W of Ws) if (!(W.wakeup.kind === "subworkflow" && [...W.calledBy].some((id) => id !== W.id))) W.outcome = decideOutcome(W, ctx);
  // A sub-workflow follows its callers: the worst caller outcome wins.
  const follow = (W, stack) => {
    if (W.outcome) return W.outcome;
    const callers = [...W.calledBy].filter((id) => id !== W.id).map((id) => ctx.byId.get(id));
    const outs = callers.filter((C) => !stack.has(C)).map((C) => ({ C, o: follow(C, new Set([...stack, W])) }));
    if (!outs.length) return (W.outcome = decideOutcome(W, ctx));
    outs.sort((a, b) => OUTCOME_RANK.indexOf(a.o.kind) - OUTCOME_RANK.indexOf(b.o.kind));
    const w = outs[0];
    W.outcome = { kind: w.o.kind, target: w.o.target, reason: `inlined into ${callers.map((C) => `"${C.name}"`).join(", ")}; follows "${w.C.name}"`, alsoTargets: [] };
    const blocking = [...W.blockers.values()].filter((b) => BLOCKING.has(b.kind));
    if (blocking.length) W.outcome = { kind: "keep-in-n8n", target: null, reason: blocking.map((b) => b.reason).join("; "), alsoTargets: [] };
    return W.outcome;
  };
  for (const W of Ws) follow(W, new Set());
  for (const W of Ws) for (const s of W.sharedState.values()) {
    const k = `${s.kind}\u0000${s.key}`;
    if (!ctx.sharedIndex.has(k)) ctx.sharedIndex.set(k, []);
    if (!ctx.sharedIndex.get(k).includes(W.id)) ctx.sharedIndex.get(k).push(W.id);
  }
  const workflows = Ws.map((W) => reportOf(W, ctx));
  return {
    schemaVersion: 1,
    analyzer: { version: VERSION, nodesMeta: nodes.meta ?? null },
    summary: summarize(workflows, ctx, inputErrors),
    workflows,
  };
}

function summarize(workflows, ctx, inputErrors) {
  const count = (xs) => xs.reduce((m, x) => ((m[x] = (m[x] || 0) + 1), m), {});
  const sortKeys = (o, order) => Object.fromEntries(Object.entries(o).sort(([a], [b]) => (order ? byOrder(order)(a, b) : 0) || a.localeCompare(b)));
  const outcomes = Object.fromEntries(OUTCOME_RANK.slice().reverse().map((k) => [k, 0]));
  for (const w of workflows) outcomes[w.outcome.kind]++;
  const cloudRuns = workflows
    .filter((w) => w.outcome.kind === "subscription" && w.outcome.target === "cloud-task" && w.schedule.runsPerDay != null)
    .reduce((a, w) => a + w.schedule.runsPerDay / 24, 0);
  return {
    workflows: workflows.length,
    outcomes,
    targets: sortKeys(count(workflows.filter((w) => w.outcome.target).map((w) => `${w.outcome.kind}:${w.outcome.target}`))),
    wakeups: sortKeys(count(workflows.map((w) => w.wakeup.kind)), WAKEUP_RANK),
    blockers: sortKeys(count(workflows.flatMap((w) => uniq(w.blockers.map((b) => b.kind)))), BLOCKER_ORDER),
    notAnAutomation: workflows.filter((w) => w.blockers.some((b) => b.kind === "not-an-automation")).length,
    questions: workflows.reduce((a, w) => a + w.questions.filter((q) => q.answer === null).length, 0),
    unmappedTypes: uniq(workflows.flatMap((w) => w.unmapped.map((u) => u.type))).sort(),
    cloudScheduledRunsPerHour: round(cloudRuns, 2),
    cloudScheduledRunsPerHourLimit: ctx.thresholds.cloudScheduledRunsPerAccountHour ?? null,
    answers: {
      used: ctx.used.size,
      unused: Object.keys(ctx.answers).filter((id) => !ctx.used.has(id) && !ctx.answerErrors.some((e) => e.id === id)).sort(),
      invalid: ctx.answerErrors,
    },
    inputErrors,
  };
}

