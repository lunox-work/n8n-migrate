function isPlaceholder(v) {
  return (
    /^(?:your|my|insert|enter|replace|put|add|paste)[\s_-]?/i.test(v) ||
    /x{4,}|X{4,}|\*{3,}|\.{3}|[<>{}[\]]/.test(v) ||
    /here|example|placeholder|dummy|changeme|redacted/i.test(v) ||
    /(.)\1{7,}/.test(v)
  );
}

export function redact(v) {
  return `${txt(v).slice(0, 4)}…${txt(v).length}`;
}

// Finds secret-looking literals in one string. In an expression string
// (starting with "=") only the literal text outside {{ }} is scanned.
// A value the converter already redacted (redactSecrets) still counts as that secret, so a
// stored export reports what the original did.
const REDACTED_MARK = /«redacted ([\w-]+) ([^»\s]*)»/g;
export function findSecrets(s) {
  const text = s.startsWith("=") ? blankExpr(s.slice(1), (m) => " ".repeat(m.length)) : s;
  const spans = [];
  const out = [];
  REDACTED_MARK.lastIndex = 0;
  for (let m; (m = REDACTED_MARK.exec(text)); ) {
    spans.push([m.index, m.index + m[0].length]);
    out.push({ kind: m[1], value: m[0], redacted: m[2] });
  }
  for (const [kind, re] of SECRET_PATTERNS) {
    re.lastIndex = 0;
    for (let m; (m = re.exec(text)); ) {
      const value = m[1] ?? m[0];
      const start = m.index + (m[1] !== undefined ? m[0].indexOf(m[1]) : 0);
      const end = start + value.length;
      if (spans.some(([a, b]) => start < b && end > a)) continue;
      if (isPlaceholder(value)) continue;
      spans.push([start, end]);
      out.push({ kind, value });
    }
  }
  return out;
}

// Walks every string under `root`; also flags {name, value} pairs whose name
// says secret (HTTP Request header and query parameter lists).
export function scanSecrets(root, path) {
  const out = [];
  const walk = (v, p) => {
    if (typeof v === "string") {
      for (const f of findSecrets(v)) out.push({ path: p, kind: f.kind, redacted: f.redacted ?? redact(f.value) });
    } else if (Array.isArray(v)) v.forEach((x, i) => walk(x, `${p}[${i}]`));
    else if (isObj(v)) {
      if (typeof v.name === "string" && typeof v.value === "string" && SECRET_NAME.test(v.name.trim()) && !v.value.startsWith("=")) {
        const val = v.value.trim();
        if (val.length >= 16 && !isPlaceholder(val) && !findSecrets(v.value).length) out.push({ path: `${p}.value`, kind: "named-param", redacted: redact(val) });
      }
      for (const [k, x] of Object.entries(v)) walk(x, `${p}.${k}`);
    }
  };
  walk(root, path);
  return out;
}

// The same walk as scanSecrets, returning a copy of `root` with every secret value replaced
// by `«redacted <kind> <first 4 chars>…<length>»` (the converter writes no secret value
// anywhere), and the list of what was replaced.
export function redactSecrets(root, path = "") {
  const found = [];
  const mark = (kind, v) => `«redacted ${kind} ${redact(v)}»`;
  const walk = (v, p) => {
    if (typeof v === "string") {
      let s = v;
      for (const f of findSecrets(v)) {
        if (f.redacted !== undefined) continue;
        found.push({ path: p, kind: f.kind, redacted: redact(f.value) });
        s = s.split(f.value).join(mark(f.kind, f.value));
      }
      return s;
    }
    if (Array.isArray(v)) return v.map((x, i) => walk(x, `${p}[${i}]`));
    if (isObj(v)) {
      const out = {};
      for (const [k, x] of Object.entries(v)) out[k] = walk(x, `${p}.${k}`);
      if (typeof v.name === "string" && typeof v.value === "string" && SECRET_NAME.test(v.name.trim()) && !v.value.startsWith("=")) {
        const val = v.value.trim();
        if (val.length >= 16 && !isPlaceholder(val) && !findSecrets(v.value).length) {
          found.push({ path: `${p}.value`, kind: "named-param", redacted: redact(val) });
          out.value = mark("named-param", val);
        }
      }
      return out;
    }
    return v;
  };
  return { value: walk(root, path), found };
}

// ---------- cron ----------

const MONTHS = ["jan", "feb", "mar", "apr", "may", "jun", "jul", "aug", "sep", "oct", "nov", "dec"];
const DAYS = ["sun", "mon", "tue", "wed", "thu", "fri", "sat"];
const CRON_FIELDS = [
  { name: "second", min: 0, max: 59 },
  { name: "minute", min: 0, max: 59 },
  { name: "hour", min: 0, max: 23 },
  { name: "day of month", min: 1, max: 31 },
  { name: "month", min: 1, max: 12, names: MONTHS, base: 1 },
  { name: "day of week", min: 0, max: 7, names: DAYS, base: 0 },
];

function cronValue(s, f) {
  if (/^\d+$/.test(s)) return Number(s);
  const i = f.names ? f.names.indexOf(s.toLowerCase()) : -1;
  if (i < 0) throw new Error(`bad ${f.name} value "${s}"`);
  return i + f.base;
}

function cronField(text, f) {
  const set = new Set();
  for (const part of text.split(",")) {
    const m = part.match(/^([^/]+)(?:\/(\d+))?$/);
    if (!m) throw new Error(`bad ${f.name} field "${text}"`);
    const step = m[2] === undefined ? 1 : Number(m[2]);
    if (step < 1) throw new Error(`bad step in ${f.name} field "${text}"`);
    let lo;
    let hi;
    if (m[1] === "*" || m[1] === "?") [lo, hi] = [f.min, f.max];
    else if (m[1].includes("-")) {
      const [a, b] = m[1].split("-");
      [lo, hi] = [cronValue(a, f), cronValue(b, f)];
    } else {
      lo = cronValue(m[1], f);
      hi = m[2] === undefined ? lo : f.max;
    }
    if (lo < f.min || hi > f.max || lo > hi) throw new Error(`${f.name} out of range in "${text}"`);
    for (let x = lo; x <= hi; x += step) set.add(x);
  }
  return set;
}

// Parses a 5-field (minute first) or 6-field (second first) cron expression,
// the two forms n8n accepts. Months are 1-12, days of week 0-7 (0 and 7 are
// Sunday), names allowed. When both day fields are restricted a day matching
// either one fires (Vixie cron). L, W and # are not supported and throw.
export function parseCron(expr) {
  if (typeof expr !== "string") throw new Error("cron expression is not a string");
  const parts = expr.trim().split(/\s+/);
  if (parts.length === 5) parts.unshift("0");
  if (parts.length !== 6) throw new Error(`cron needs 5 or 6 fields, got ${parts.length}`);
  const sets = parts.map((p, i) => cronField(p, CRON_FIELDS[i]));
  if (sets[5].has(7)) {
    sets[5].delete(7);
    sets[5].add(0);
  }
  const sorted = (s) => [...s].sort((a, b) => a - b);
  return {
    seconds: sorted(sets[0]),
    minutes: sorted(sets[1]),
    hours: sorted(sets[2]),
    doms: sets[3],
    months: sets[4],
    dows: sets[5],
    domStar: parts[3].startsWith("*") || parts[3] === "?",
    dowStar: parts[5].startsWith("*") || parts[5] === "?",
  };
}

function cronDayMatches(c, dom, month, dow) {
  if (!c.months.has(month)) return false;
  if (c.domStar && c.dowStar) return true;
  if (c.domStar) return c.dows.has(dow);
  if (c.dowStar) return c.doms.has(dom);
  return c.doms.has(dom) || c.dows.has(dow);
}

// Simulates the expressions together, in UTC, from the start of the day of
// `nowMs`: 7 days, or 366 days when that gives fewer than 168 fires (sparse
// schedules need the longer window to be counted fairly). Returns runs per day
// and the shortest gap between two fires (null with fewer than two fires).
// Timezone and DST are ignored: they move fires, not their count
// (computeSchedule sets schedule.dstNote where DST can move a run).
export function simulateCron(exprs, nowMs) {
  const parsed = exprs.map(parseCron);
  const now = new Date(nowMs);
  const start = Date.UTC(now.getUTCFullYear(), now.getUTCMonth(), now.getUTCDate());
  const run = (days) => {
    let count = 0;
    let last = null;
    let minGap = null;
    for (let di = 0; di < days; di++) {
      const day = new Date(start + di * 86400000);
      const [dom, month, dow] = [day.getUTCDate(), day.getUTCMonth() + 1, day.getUTCDay()];
      let times = [];
      for (const c of parsed) {
        if (!cronDayMatches(c, dom, month, dow)) continue;
        for (const h of c.hours) for (const m of c.minutes) for (const s of c.seconds) times.push(h * 3600 + m * 60 + s);
      }
      if (parsed.length > 1) times = uniq(times).sort((a, b) => a - b);
      for (const t of times) {
        const ts = di * 86400 + t;
        if (last !== null && (minGap === null || ts - last < minGap)) minGap = ts - last;
        last = ts;
        count++;
      }
    }
    return { count, minGap, days };
  };
  let r = run(7);
  if (r.count < 7 * 24) r = run(366);
  return { runsPerDay: r.count / r.days, shortestSec: r.minGap, fires: r.count, days: r.days };
}

// ---------- schedule rules ----------

const hasExpr = (v) => allStrings(v).some(isExpr);

// n8n-workflow toCronExpression() for the legacy Cron node's triggerTimes and
// for poll triggers' pollTimes. n8n picks a random second (and a random minute
// for everyX hours); 0 stands in for both. Defaults are the parameter defaults
// of cronNodeOptions: mode everyDay, hour 14, minute 0, dayOfMonth 1,
// weekday 1, value 2, unit hours, cronExpression "* * * * * *".
export function legacyCron(item) {
  const i = isObj(item) ? item : {};
  const mode = i.mode ?? "everyDay";
  const hour = i.hour ?? 14;
  const minute = i.minute ?? 0;
  if (mode === "everyMinute") return "0 * * * * *";
  if (mode === "everyHour") return `0 ${minute} * * * *`;
  if (mode === "everyX") {
    const value = i.value ?? 2;
    if ((i.unit ?? "hours") === "minutes") return `0 */${value} * * * *`;
    return `0 0 */${value} * * *`;
  }
  if (mode === "everyDay") return `0 ${minute} ${hour} * * *`;
  if (mode === "everyWeek") return `0 ${minute} ${hour} * * ${i.weekday ?? "1"}`;
  if (mode === "everyMonth") return `0 ${minute} ${hour} ${i.dayOfMonth ?? 1} * *`;
  return txt(i.cronExpression, "* * * * * *").trim();
}

// Schedule Trigger rule items, after withIntervalDefaults() and
// toCronExpression() in the n8n package (nodes/Schedule/GenericFunctions).
// seconds and cronExpression become cron strings. The other fields are exact
// rhythms because n8n's recurrenceCheck enforces the interval even where the
// cron step does not divide evenly. months use 28 days per month as the
// shortest gap and 30.44 for runs per day.
function scheduleRuleTimes(item) {
  const i = isObj(item) ? item : {};
  const field = ["seconds", "minutes", "hours", "days", "weeks", "months", "cronExpression"].includes(i.field) ? i.field : "days";
  const fixed = (sec) => ({ fixed: { runsPerDay: 86400 / sec, shortestSec: sec } });
  switch (field) {
    case "seconds":
      return { cron: `*/${i.secondsInterval ?? 30} * * * * *` };
    case "minutes":
      return fixed((i.minutesInterval ?? 5) * 60);
    case "hours":
      return fixed((i.hoursInterval ?? 1) * 3600);
    case "days":
      return fixed((i.daysInterval ?? 1) * 86400);
    case "weeks": {
      const n = i.weeksInterval ?? 1;
      let days = uniq([].concat(i.triggerAtDay ?? [0]).map(Number)).sort((a, b) => a - b);
      if (!days.length) days = [0, 1, 2, 3, 4, 5, 6];
      const gaps = days.slice(1).map((d, k) => d - days[k]);
      if (n === 1) gaps.push(days[0] + 7 - days.at(-1));
      const shortestDays = gaps.length ? Math.min(...gaps) : 7 * n;
      return { fixed: { runsPerDay: days.length / (7 * n), shortestSec: shortestDays * 86400 } };
    }
    case "months": {
      const n = i.monthsInterval ?? 1;
      return { fixed: { runsPerDay: 1 / (30.4375 * n), shortestSec: 28 * 86400 * n } };
    }
    case "cronExpression":
      return { cron: txt(i.expression) };
  }
}

// Whether a time trigger fires at a time of day (so its timezone matters),
// as opposed to every N seconds, minutes or hours. Unreadable settings count
// as mattering.
const cronHasTimeOfDay = (c) => {
  const p = txt(c).trim().split(/\s+/);
  if (p.length === 5) p.unshift("0");
  if (p.length !== 6) return true;
  return !/^\*(\/\d+)?$/.test(p[2]) || [p[3], p[4], p[5]].some((x) => !/^[*?]$/.test(x));
};
function timeOfDayMatters(d) {
  const p = d.params;
  if (d.type === "n8n-nodes-base.interval") return false;
  if (d.type === "n8n-nodes-base.scheduleTrigger") {
    const items = [].concat((p.rule ?? { interval: [{ field: "days" }] }).interval ?? []);
    return items.some((i) => {
      const f = isObj(i) ? i.field ?? "days" : "days";
      if (["seconds", "minutes", "hours"].includes(f)) return false;
      return f === "cronExpression" ? cronHasTimeOfDay(i.expression ?? "") : true;
    });
  }
  const coll = d.type === "n8n-nodes-base.cron" ? p.triggerTimes ?? {} : p.pollTimes ?? { item: [{ mode: "everyMinute" }] };
  return [].concat(isObj(coll) ? coll.item ?? [] : []).some((i) => {
    const mode = isObj(i) ? i.mode ?? "everyDay" : "everyDay";
    if (["everyMinute", "everyHour", "everyX"].includes(mode)) return false;
    return mode === "custom" ? cronHasTimeOfDay(i.cronExpression ?? "") : true;
  });
}

// Fire times of one time-based trigger: {crons, fixed, error}.
function triggerTimes(d) {
  const p = d.params;
  const out = { crons: [], fixed: [], error: null };
  try {
    if (d.type === "n8n-nodes-base.scheduleTrigger") {
      const rule = p.rule ?? { interval: [{ field: "days" }] };
      if (hasExpr(rule)) throw new Error("the schedule is set by an expression");
      for (const item of [].concat(rule.interval ?? [])) {
        const r = scheduleRuleTimes(item);
        if (r.cron !== undefined) {
          if (!r.cron.trim()) throw new Error("empty cron expression");
          parseCron(r.cron);
          out.crons.push(r.cron);
        } else out.fixed.push(r.fixed);
      }
    } else if (d.type === "n8n-nodes-base.interval") {
      if (hasExpr([p.interval, p.unit])) throw new Error("the interval is set by an expression");
      const n = num(p.interval, 1);
      const unit = { seconds: 1, minutes: 60, hours: 3600 }[p.unit ?? "seconds"];
      if (!(n > 0) || !unit) throw new Error("invalid interval");
      out.fixed.push({ runsPerDay: 86400 / (n * unit), shortestSec: n * unit });
    } else {
      // Legacy Cron node: triggerTimes. Poll triggers: pollTimes, default
      // every minute (also used for an IMAP trigger's Gmail substitute).
      const coll = d.type === "n8n-nodes-base.cron" ? p.triggerTimes ?? {} : p.pollTimes ?? { item: [{ mode: "everyMinute" }] };
      if (hasExpr(coll)) throw new Error("the schedule is set by an expression");
      for (const item of [].concat(coll.item ?? [])) {
        const c = legacyCron(item);
        parseCron(c);
        out.crons.push(c);
      }
    }
  } catch (e) {
    out.error = e.message;
  }
  return out;
}

// ---------- graph ----------

// Number of regular main outputs; with onError continueErrorOutput the error
// output comes right after them. Multi-output nodes are listed; every other
// node has one.
function regularOutputs(d) {
  const p = d.params;
  switch (d.baseType) {
    case "n8n-nodes-base.if":
      return 2;
    case "n8n-nodes-base.compareDatasets":
      return 4;
    case "n8n-nodes-base.splitInBatches":
      return d.typeVersion >= 3 ? 2 : 1;
    case "n8n-nodes-base.switch":
      if (d.typeVersion < 3) return 4;
      if (p.mode === "expression") return num(p.numberOutputs, 4) || 4;
      return ((p.rules?.values ?? []).length || 1) + (p.options?.fallbackOutput === "extra" ? 1 : 0);
    case "@n8n/n8n-nodes-langchain.textClassifier":
      return ((p.categories?.categories ?? []).length || 1) + (p.options?.fallback === "other" ? 1 : 0);
    default:
      return 1;
  }
}

function buildGraph(wf, infos) {
  const mainOut = new Map(); // name -> [[target names] per output]
  const attach = new Map(); // sub-node name -> [root names]
  const incoming = new Set();
  const conns = isObj(wf.connections) ? wf.connections : {};
  for (const [src, types] of Object.entries(conns)) {
    if (!infos.has(src) || !isObj(types)) continue;
    for (const [ctype, outputs] of Object.entries(types)) {
      if (!Array.isArray(outputs)) continue;
      outputs.forEach((list, i) => {
        for (const c of Array.isArray(list) ? list : []) {
          const dst = c?.node;
          if (!infos.has(dst)) continue;
          if (ctype === "main") {
            if (!mainOut.has(src)) mainOut.set(src, []);
            const o = mainOut.get(src);
            while (o.length <= i) o.push([]);
            o[i].push(dst);
            incoming.add(dst);
          } else {
            if (!attach.has(src)) attach.set(src, []);
            attach.get(src).push(dst);
          }
        }
      });
    }
  }
  return { mainOut, attach, incoming };
}

function errorOutputIndex(d) {
  return d.node.onError === "continueErrorOutput" ? regularOutputs(d) : -1;
}

// Breadth-first over main connections. skipError leaves out error outputs.
function reach(starts, graph, infos, skipError) {
  const seen = new Set(starts);
  const queue = [...starts];
  while (queue.length) {
    const n = queue.shift();
    const outs = graph.mainOut.get(n) || [];
    const errIdx = skipError ? errorOutputIndex(infos.get(n)) : -1;
    outs.forEach((list, i) => {
      if (i === errIdx) return;
      for (const t of list) if (!seen.has(t)) seen.add(t), queue.push(t);
    });
  }
  return seen;
}

// Adds sub-nodes (ai_* connections, transitively) attached to nodes in `set`.
function withSubnodes(set, graph) {
  const out = new Set(set);
  for (let changed = true; changed; ) {
    changed = false;
    for (const [sub, roots] of graph.attach) if (!out.has(sub) && roots.some((r) => out.has(r))) out.add(sub), (changed = true);
  }
  return out;
}

// Branch of every node: main (runs when an enabled trigger fires), error-output
// (only behind an onError continueErrorOutput output), error-trigger (only
// behind an Error Trigger), unreached. Disabled nodes pass data through, as in
// n8n, but disabled triggers do not fire. With no enabled trigger the entry
// points are the nodes without input (n8n's manual run). Unmapped nodes
// without input are entry points too: they may be triggers we cannot read.
function computeBranches(W) {
  const { infos, order, graph } = W;
  const usable = order.filter((n) => !infos.get(n).disabled && infos.get(n).role !== "annotation");
  const entries = [];
  const errorEntries = [];
  for (const n of usable) {
    const d = infos.get(n);
    if (d.isTrigger) (d.wakeup === "error" ? errorEntries : entries).push(n);
  }
  const isRoot = (n) => !graph.incoming.has(n) && !graph.attach.has(n);
  if (!entries.length && !errorEntries.length) {
    for (const n of usable) if (isRoot(n) && infos.get(n).role !== "subnode") entries.push(n);
  } else {
    for (const n of usable) if (infos.get(n).status !== "mapped" && isRoot(n) && !entries.includes(n)) entries.push(n);
  }
  const main = withSubnodes(reach(entries, graph, infos, true), graph);
  const errStarts = [];
  for (const n of main) {
    const d = infos.get(n);
    const idx = errorOutputIndex(d);
    if (idx >= 0) for (const t of (graph.mainOut.get(n) || [])[idx] || []) if (!main.has(t)) errStarts.push(t);
  }
  const errOut = withSubnodes(reach(errStarts, graph, infos, false), graph);
  const errTrig = withSubnodes(reach(errorEntries, graph, infos, false), graph);
  const branch = new Map();
  for (const n of order) branch.set(n, main.has(n) ? "main" : errOut.has(n) ? "error-output" : errTrig.has(n) ? "error-trigger" : "unreached");
  W.branch = branch;
  W.entries = entries;
}

// ---------- capabilities ----------

function surfacesFrom(spec) {
  const out = {};
  for (const s of SURFACES) out[s] = spec?.[s]?.value ?? "no";
  return out;
}

// Each operation is looked up in the connector's operation table. An
// unlisted one waits for a check. One whose connector has no tool for it
// (confirmed "no-tool") falls back to the app's own REST API with a stored
// secret: the surfaces of requirements.connector-api, worse than the
// connector's own wherever they differ.
function connectorSurfaces(caps, name, ops) {
  const c = own(caps.connectors, name);
  const base = c ? surfacesFrom(c.surfaces) : { cloudTask: "ok", localTask: "ok", artifact: "ok" };
  const entry = ({ type, op }) => own(own(c?.operations, type)?.ops, op);
  const unlisted = !c || ops.length === 0 || ops.some((o) => !entry(o));
  const noTool = ops.filter((o) => entry(o)?.confirmed === "no-tool");
  const fallback = surfacesFrom(caps.requirements?.["connector-api"]);
  const out = {};
  for (const s of SURFACES) {
    const vals = [base[s]];
    if (unlisted && base[s] === "ok") vals.push("needs:connector-operation-check");
    if (noTool.length) vals.push(fallback[s]);
    out[s] = vals.includes("no") ? "no" : vals.filter((v) => v !== "ok").pop() ?? "ok";
  }
  const confirmed = !unlisted && ops.every((o) => entry(o).confirmed === "observed");
  return { surfaces: out, confirmed, noTool: uniq(noTool.map((x) => `${shortType(x.type)} ${x.op}`)).sort() };
}

// ---------- per-workflow analysis ----------

function newWorkflow(item, ctx, parent = null, prefix = "") {
  const wf = item.wf;
  const infos = new Map();
  const order = [];
  const duplicates = new Set();
  for (const node of Array.isArray(wf.nodes) ? wf.nodes : []) {
    if (!isObj(node)) continue;
    const d = describeNode(ctx.catalogue, node);
    applyHostRules(d, ctx.hosts);
    // n8n keeps names unique and connections refer to names: a repeated name
    // makes the export ambiguous. The first node is analysed; a blocker says so.
    if (infos.has(d.name)) {
      duplicates.add(d.name);
      continue;
    }
    infos.set(d.name, d);
    order.push(d.name);
  }
  return {
    id: item.id,
    name: item.name,
    file: item.file ?? null,
    wf,
    parent,
    // Inline sub-workflows: "<call node> › " (nested: chained), so their
    // nodes can be named in the top workflow's questions and credentials.
    prefix,
    duplicates: [...duplicates],
    pendingWrites: [],
    settings: isObj(wf.settings) ? wf.settings : {},
    infos,
    order,
    graph: buildGraph(wf, infos),
    req: new Map(),
    blockers: new Map(),
    questions: [],
    sharedState: new Map(),
    calls: [],
    calledBy: new Set(),
    levers: new Set(),
    unmapped: [],
    callModelNodes: new Set(),
  };
}

function addReq(W, kind, name, nodeName, extra = {}) {
  const key = `${kind}\u0000${name}`;
  if (!W.req.has(key)) W.req.set(key, { kind, name, nodes: new Set(), ops: [], ...extra });
  const r = W.req.get(key);
  if (nodeName != null) r.nodes.add(nodeName);
  if (extra.ops) for (const o of extra.ops) if (!r.ops.some((x) => x.type === o.type && x.op === o.op)) r.ops.push(o);
  if (extra.creds) r.creds = uniq([...(r.creds || []), ...extra.creds]);
  if (extra.note && !r.note) r.note = extra.note;
  return r;
}

function addBlocker(W, kind, reason, nodeName) {
  const key = `${kind}\u0000${reason}`;
  if (!W.blockers.has(key)) W.blockers.set(key, { kind, reason, nodes: new Set() });
  if (nodeName != null) W.blockers.get(key).nodes.add(nodeName);
}

function addShared(W, kind, name, nodeName, key = name) {
  const k = `${kind}\u0000${name}`;
  if (!W.sharedState.has(k)) W.sharedState.set(k, { kind, name, key, nodes: new Set() });
  W.sharedState.get(k).nodes.add(nodeName);
}

// Records a question and returns {value, answered}: value is the person's
// answer when valid, else the assumed value. Question ids are `<workflow id>/<kind>` plus
// `/<node name>` for node questions, so answers survive re-runs.
function ask(W, ctx, kind, nodeName, q) {
  const owner = W.parent ? W.parent : W;
  const path = nodeName ? `${W.prefix}${nodeName}` : null;
  const id = path ? `${owner.id}/${kind}/${path}` : `${owner.id}/${kind}`;
  const prev = owner.questions.find((x) => x.id === id);
  if (prev) return { value: prev.value, answered: prev.answer !== null };
  const question = { id, text: q.text, nodes: q.nodes ?? (path ? [path] : []), affects: q.affects, answerType: q.answerType, options: q.options, assumed: q.assumed, answer: null };
  let value = q.assumed;
  if (Object.prototype.hasOwnProperty.call(ctx.answers, id)) {
    const raw = ctx.answers[id];
    const norm = normalizeAnswer(raw, q);
    if (norm.ok) {
      question.answer = norm.value;
      value = norm.value;
      ctx.used.add(id);
    } else ctx.answerErrors.push({ id, reason: norm.reason });
  }
  owner.questions.push({ ...question, value });
  return { value, answered: question.answer !== null };
}

function normalizeAnswer(raw, q) {
  if (q.answerType === "nodes") {
    // true: every listed node; false: none; else the node names, as a list or
    // comma-separated text.
    if (typeof raw === "boolean") return { ok: true, value: raw };
    const s = typeof raw === "string" ? raw.trim().toLowerCase() : null;
    if (s === "yes" || s === "true" || s === "all") return { ok: true, value: true };
    if (s === "no" || s === "false" || s === "none") return { ok: true, value: false };
    const names = Array.isArray(raw) ? raw.map((x) => txt(x).trim()) : typeof raw === "string" ? raw.split(",").map((x) => x.trim()) : null;
    if (!names || !names.length || names.some((n) => !n)) return { ok: false, reason: "expected true, false or a list of the node names" };
    const bad = names.filter((n) => !q.nodes.includes(n));
    if (bad.length) return { ok: false, reason: `not among the listed nodes: ${bad.join(", ")}` };
    return { ok: true, value: uniq(names).sort(byOrder(q.nodes)) };
  }
  if (q.answerType === "boolean") {
    if (typeof raw === "boolean") return { ok: true, value: raw };
    const s = txt(raw).trim().toLowerCase();
    if (["yes", "true"].includes(s)) return { ok: true, value: true };
    if (["no", "false"].includes(s)) return { ok: true, value: false };
    return { ok: false, reason: "expected true or false" };
  }
  if (q.answerType === "choice") {
    if (Object.keys(q.options).includes(txt(raw))) return { ok: true, value: txt(raw) };
    return { ok: false, reason: `expected one of ${Object.keys(q.options).join(", ")}` };
  }
  if (raw === null || raw === undefined || isObj(raw) || Array.isArray(raw) || txt(raw).trim() === "") return { ok: false, reason: "expected text" };
  return { ok: true, value: txt(raw).trim() };
}

// Credential types whose requests go to the person's own site (the base URL lives in the n8n
// credential, which an export never carries). n8n-nodes-base 2.47.7: WordpressApi.credentials
// `url`, GenericFunctions wordpressApiRequest `${credentials.url}/wp-json/wp/v2${resource}`;
// N8nApi.credentials `baseUrl` (placeholder https://<name>.app.n8n.cloud/api/v1), the n8n
// node's requestDefaults baseURL = baseUrl without a trailing "/". One question per such
// credential: the site's address, as in the credential; the converter builds the requests on
// it and sends the secret only to its host (convert.mjs siteBase(); `defaultPath` is added to
// an answer with no path, as n8n's public API always lives under /api/v1).
// A site on a local address (localhost, a private or link-local IP, a .local or internal
// name, a name without a dot: runtime engine.mjs localHost) is out of a cloud task's reach:
// the answer adds a `local-network` requirement, whose surfaces (capabilities.json) move the
// workflow to a local task, as files on the n8n host's disk do (`host-disk`).
export const SITE_CREDENTIALS = {
  wordpressApi: { field: "URL", label: "WordPress", example: "https://example.com" },
  n8nApi: { field: "Base URL", label: "n8n", example: "https://n8n.example.com/api/v1", defaultPath: "/api/v1", extra: "These steps keep calling your n8n instance, so they work only while it keeps running." },
};
// The host name and host (with its port) of a site answer (an absolute http(s) URL), or null.
export function siteHost(answer) {
  try {
    const u = new URL(String(answer ?? "").trim());
    return /^https?:$/.test(u.protocol) && u.hostname ? { hostname: u.hostname.toLowerCase(), host: u.host.toLowerCase() } : null;
  } catch {
    return null;
  }
}
function askSites(W, ctx) {
  for (const c of W.credentials ?? []) {
    const site = SITE_CREDENTIALS[c.type];
    if (!site) continue;
    const nodes = c.nodes.map((n) => `${W.prefix}${n}`);
    const { value, answered } = ask(W, ctx, "site", c.name, {
      text: `Which ${site.label} site does the credential "${c.name}" point to? Give its address as in the n8n credential (its ${site.field} field, for example ${site.example}). Requests and the credential go only to that site. An address on your own computer or network (localhost, a private IP, a .local or internal name) makes it a local task, since a cloud task cannot reach it.${site.extra ? ` ${site.extra}` : ""}`,
      nodes,
      affects: "allow.http",
      answerType: "text",
      options: { "<site address>": "the site the steps' requests and the credential go to" },
      assumed: null,
    });
    const h = answered ? siteHost(value) : null;
    if (h && localHost(h.hostname)) for (const n of c.nodes) addReq(W, "local-network", `${site.label} at ${h.host}`, n, { surfaces: surfacesFrom(ctx.capabilities.requirements?.["local-network"]) });
  }
}

// Database steps the runtime runs itself (runtime postgres.mjs, with the vendored node-postgres
// in a task): the Postgres node v2's executeQuery and table operations (select, insert, update,
// upsert, deleteTable), as a step or an agent tool. The connection
// lives in the n8n credential (host, port, database, user, password, SSL), which an export never
// carries, so one question per such credential asks for it as a connection URL without the
// password (the password is the credential's stored secret). A database on a local address
// adds a local-network requirement, as a site answer does.
export const DB_RUNTIME_OPS = { "n8n-nodes-base.postgres": { versions: [2, 3], operations: ["executeQuery", "select", "insert", "update", "upsert", "deleteTable"], defaultOperation: "insert", label: "Postgres" } };
export function dbRuntimeStep(d) {
  const spec = Object.prototype.hasOwnProperty.call(DB_RUNTIME_OPS, d?.baseType ?? "") ? DB_RUNTIME_OPS[d.baseType] : null;
  if (!spec) return null;
  const v = Number(d.typeVersion ?? d.version ?? 1);
  const op = d.operation ?? spec.defaultOperation;
  return v >= spec.versions[0] && v < spec.versions[1] && spec.operations.includes(op) ? spec : null;
}
// "postgres://user@host:5432/database?sslmode=require" -> {host, port, database, user, ssl}, or
// null. No password: it is the stored secret, never part of the answer.
export function dbConnection(answer) {
  let u;
  try {
    u = new URL(String(answer ?? "").trim());
  } catch {
    return null;
  }
  if (!/^postgres(ql)?:$/.test(u.protocol) || !u.hostname || u.password) return null;
  const database = decodeURIComponent(u.pathname.replace(/^\//, ""));
  if (!database || database.includes("/")) return null;
  const sslmode = u.searchParams.get("sslmode") ?? "disable";
  if (![...u.searchParams.keys()].every((k) => k === "sslmode") || !["disable", "require", "verify-full", "no-verify"].includes(sslmode)) return null;
  return { host: u.hostname.replace(/^\[|\]$/g, "").toLowerCase(), port: Number(u.port || 5432), database, user: decodeURIComponent(u.username || ""), ssl: sslmode };
}
function askDatabases(W, ctx) {
  for (const c of W.credentials ?? []) {
    const nodes = c.nodes.filter((n) => dbRuntimeStep(W.infos.get(n)));
    if (!nodes.length) continue;
    const spec = dbRuntimeStep(W.infos.get(nodes[0]));
    const { value, answered } = ask(W, ctx, "database", c.name, {
      text: `Which ${spec.label} database does the credential "${c.name}" connect to? Give it as a connection URL without the password, from the n8n credential's Host, Port, Database and User fields: postgres://<user>@<host>:<port>/<database> (add ?sslmode=require to use SSL, ?sslmode=no-verify to use SSL without checking the server's certificate). The password is stored as the credential's secret at setup. The steps run SQL with that user's rights, so give it only the rights the workflow needs. A database on your own computer or network (localhost, a private IP, a .local or internal name) makes it a local task.`,
      nodes: nodes.map((n) => `${W.prefix}${n}`),
      affects: "allow.db",
      answerType: "text",
      options: { "<connection URL>": "the database the steps connect to" },
      assumed: null,
    });
    const conn = answered ? dbConnection(value) : null;
    if (answered && !conn) ctx.answerErrors.push({ id: `${(W.parent || W).id}/database/${W.prefix}${c.name}`, reason: "expected postgres://<user>@<host>:<port>/<database>, no password, with ?sslmode= only" });
    if (conn && localHost(conn.host)) for (const n of nodes) addReq(W, "local-network", `${spec.label} at ${conn.host}:${conn.port}`, n, { surfaces: surfacesFrom(ctx.capabilities.requirements?.["local-network"]) });
  }
}

// HTTP Request steps (v3 and later) and RSS Read steps whose address comes from data at run time
// (a URL expression that writes no address of its own: runtime/src/convert.mjs openHost). n8n sends them to any host; the folder
// sends them only where the person says at setup: the hosts it may reach, or "public" (any
// public https host; private, loopback, link-local and metadata addresses are always refused,
// and only for a GET or HEAD request without a credential). Unanswered, preflight refuses the
// step (convert.mjs hostsQuestion()).
function askHosts(W, ctx) {
  for (const n of W.order) {
    const d = W.infos.get(n);
    if (!d || d.disabled) continue;
    const http = d.baseType === "n8n-nodes-base.httpRequest" && d.kind !== "model" && !d.levers?.includes("llm-api") && (d.typeVersion ?? 1) >= 3;
    // RSS Read as a step (a GET without a credential); the agent tool's URL comes from the model.
    const rss = d.type === "n8n-nodes-base.rssFeedRead" && d.role === "step";
    if (!http && !rss) continue;
    if (!openHost(d.params?.url)) continue;
    ask(W, ctx, "hosts", d.name, {
      text: `The step "${d.name}" takes its address from data at run time, so its host is not known before a run. Which hosts may it reach? Name them, comma-separated (for example api.example.com, cdn.example.com), or answer "public" to let it reach any public https host, as a scraper that visits sites from a list needs; private, loopback, link-local and cloud-metadata addresses are always refused, and "public" is accepted only for a GET or HEAD request that sends no credential. Any other host is refused at run time.`,
      affects: "allow.http",
      answerType: "text",
      options: { "<hosts>": "only these hosts, comma-separated", public: "any public https host (data picks the site)" },
      assumed: null,
    });
  }
}

// Effect questions and parsing that need the workflow (answers live there).
function settleEffect(W, d, ctx) {
  if (d.effect !== undefined || d.status !== "mapped") return;
  if (d.kind === "code") {
    const e = codeEffect(d.params);
    if (e) (d.effect = e), (d.effectBy = "parse");
    return;
  }
  // An SQL statement or HTTP request the file cannot settle counts as a write
  // (run safety guards writes) and joins the workflow's one writes question.
  const pending = (what) => {
    d.effect = "write";
    d.effectBy = "assumed";
    (W.parent || W).pendingWrites.push({ d, path: `${W.prefix}${d.name}`, what });
  };
  if (d.operation === "executeQuery" && d.kind === "db") {
    const e = sqlEffect(d.params.query);
    if (e) {
      d.effect = e;
      d.effectBy = "parse";
      return;
    }
    pending("SQL built by an expression");
    return;
  }
  if (HTTP_QUESTION_TYPES.has(d.baseType)) {
    const method = d.params.method ?? d.params.requestMethod ?? "GET";
    pending(isExpr(method) ? "method set by an expression" : `${txt(method)} request`);
  }
}

// One question per workflow for every step whose effect was assumed: which
// of them change data at the other end.
function askWrites(W, ctx) {
  const list = W.pendingWrites;
  if (!list.length) return;
  const names = list.map((p) => p.path);
  const quoted = list.map((p) => `"${p.path}" (${p.what})`);
  const joined = quoted.length > 1 ? `${quoted.slice(0, -1).join(", ")} and ${quoted.at(-1)}` : quoted[0];
  const text =
    list.length === 1
      ? `Does ${joined} change data at the other end? Until you answer, it counts as a write.`
      : `Which of these change data at the other end: ${joined}? Until you answer, ${list.length === 2 ? "both" : `all ${list.length}`} count as writes.`;
  const a = ask(W, ctx, "writes", null, {
    text,
    nodes: names,
    affects: "effect",
    answerType: "nodes",
    options: { true: "every listed step writes", false: "none writes: all read", "<node names>": "only these write; the rest read" },
    assumed: true,
  });
  if (!a.answered) return;
  for (const p of list) {
    p.d.effect = a.value === true || (Array.isArray(a.value) && a.value.includes(p.path)) ? "write" : "read";
    p.d.effectBy = "answer";
  }
}

function credentialNames(d) {
  const c = d.node.credentials;
  if (!isObj(c)) return [];
  return Object.entries(c).map(([type, v]) => ({ type, name: txt(isObj(v) ? v.name : v, type) }));
}

function rlValue(v) {
  if (isObj(v)) return { value: v.value, cached: v.cachedResultName };
  return { value: v, cached: undefined };
}

function mcpHost(d) {
  const url = d.params.endpointUrl ?? d.params.sseEndpoint ?? d.params.url;
  if (typeof url !== "string" || !url) return "unnamed MCP server";
  if (isExpr(url)) return "MCP server set by an expression";
  try {
    return new URL(url).host || "unnamed MCP server";
  } catch {
    return "unnamed MCP server";
  }
}

function substitutionFor(d, ctx) {
  const s = own(ctx.capabilities.substitutions, d.baseType);
  if (!s) return null;
  const ops = s.operations || ["*"];
  if (!ops.includes("*") && !ops.includes(d.opKey) && !ops.includes(d.operation)) return null;
  return s;
}

// Why a mapped node cannot run on Claude, or null.
function blockedReason(d) {
  if (d.kind === "blocked") return d.reason || `${shortType(d.type)} is not supported`;
  if (d.role === "n8n-internal" && !TRAINING_TYPES.has(d.baseType) && d.effect !== "none") return `n8n-internal node: ${d.notes || shortType(d.type)}`;
  return null;
}

export const N8N_STAYS_NOTE = "keeps calling your n8n instance through its public API (reads only), so it is useful only while n8n keeps running";

// Requirements, blockers and shared state contributed by one node.
function processNode(W, d, ctx, br) {
  const name = d.name;
  if (br === "unreached") return;
  const keep = br === "main" || br === "error-output";
  if (d.status !== "mapped") {
    const reason = d.status === "not-in-catalogue" ? `${d.type} is not in the node catalogue` : `${d.type} has no mapping`;
    if (br === "main") addBlocker(W, "unmapped", reason, name);
    else addBlocker(W, "dropped-branch", `only on an error branch: ${reason}`, name);
    return;
  }
  if (d.wakeup === "error") {
    addBlocker(W, "dropped-branch", "the runner's failure alert replaces error workflows", name);
    return;
  }
  const blocked = blockedReason(d);
  if (blocked) {
    if (br !== "main") {
      addBlocker(W, "dropped-branch", `only on an error branch: ${blocked}`, name);
      return;
    }
    const sub = substitutionFor(d, ctx);
    if (sub) {
      addBlocker(W, "substitution", `${sub.name}: ${sub.to}`, name);
      addReq(W, "substitution", sub.name, name, { surfaces: surfacesFrom(sub.surfaces) });
    } else addBlocker(W, "unsupported", blocked, name);
    for (const l of d.levers) W.levers.add(l);
    return;
  }
  if (!keep) return;
  for (const l of d.levers) W.levers.add(l);
  settleEffect(W, d, ctx);
  const caps = ctx.capabilities;
  const reqSurf = (k) => surfacesFrom(caps.requirements?.[k]);

  if (d.isTrigger) {
    // A poll, chat, form or relay wake-up needs the lever of the same name,
    // also when the mapping sets the wake-up by a rule (webhook).
    if (["poll", "chat", "form", "relay"].includes(d.wakeup)) W.levers.add(d.wakeup);
    if (d.wakeup === "relay") addReq(W, "relay", shortType(d.type), name, { surfaces: reqSurf("relay") });
    if (d.wakeup === "poll") addReq(W, "poll", shortType(d.type), name, { surfaces: reqSurf("poll") });
    if (d.connector) addReq(W, "connector", d.connector, name, { ops: [{ type: d.baseType, op: "poll" }] });
  }
  switch (d.kind) {
    case "connector":
      if (d.connector === "custom-mcp") addReq(W, "mcp-server", mcpHost(d), name, { surfaces: reqSurf("mcp-server") });
      else addReq(W, "connector", d.connector, name, { ops: [{ type: d.baseType, op: d.opKey ?? "?" }], creds: credentialNames(d).map((c) => c.name) });
      break;
    case "model":
    case "agent":
      if (d.role === "step") addReq(W, "model", "claude", name, { surfaces: reqSurf("model") });
      if (d.llmApi) {
        const sub = caps.httpSubstitutions?.model;
        addReq(W, "substitution", sub?.name ?? "model call → Claude", name, { surfaces: surfacesFrom(sub?.surfaces) });
      }
      if (d.baseType === "@n8n/n8n-nodes-langchain.memoryBufferWindow") {
        addShared(W, "process-memory", "chat memory in the n8n process", name);
        addReq(W, "state", "chat-memory", name, { surfaces: reqSurf("state") });
      }
      break;
    case "http":
    case "media":
      addReq(W, "http", "outbound http", name, { surfaces: reqSurf("http") });
      break;
    case "db":
      if (d.baseType === "n8n-nodes-base.dataTable") {
        // Tables are matched across workflows by name when the export names
        // them (a create's tableName, a cached name, mode name), else by id.
        // A table chosen at run time matches nothing.
        const { value, cached } = rlValue(d.params.dataTableId);
        const mode = isObj(d.params.dataTableId) ? d.params.dataTableId.mode : null;
        const literal = (x) => x != null && !isObj(x) && !isExpr(x) && txt(x).trim() !== "";
        const tableName = d.resource === "table" && d.operation === "create" ? d.params.tableName : cached ?? (mode === "name" ? value : undefined);
        let label;
        let key;
        if (literal(tableName)) (label = txt(tableName)), (key = `name:${label}`);
        else if (literal(value) && tableName === undefined) (label = txt(value)), (key = `id:${label}`);
        else (label = "a table chosen at run time"), (key = `run-time:${W.id}:${name}`);
        addShared(W, "data-table", label, name, key);
        addReq(W, "state", `data-table:${label}`, name, { surfaces: reqSurf("state") });
      } else if (d.baseType === "n8n-nodes-base.removeDuplicates") {
        const scope = txt(d.params.options?.scope, "node");
        addShared(W, "dedupe-history", `scope ${scope}`, name);
        addReq(W, "state", `dedupe-history:${scope}`, name, { surfaces: reqSurf("state") });
      } else {
        if (/\.memory[A-Z]/.test(d.baseType)) addShared(W, "chat-memory", shortType(d.baseType), name);
        // A database step the runtime runs itself (askDatabases) needs a task that can open a
        // connection; any other waits for a database connector or the bundled server.
        if (dbRuntimeStep(d)) addReq(W, "db-client", shortType(d.baseType), name, { surfaces: reqSurf("db-client") });
        else addReq(W, "db", shortType(d.baseType), name, { surfaces: reqSurf("db") });
      }
      break;
    case "vector":
      if (/vectorStoreInMemory/.test(d.baseType)) {
        const { value } = rlValue(d.params.memoryKey);
        const key = value != null && !isExpr(value) ? txt(value) : "vector_store_key";
        addShared(W, "vector-memory", key, name);
        addReq(W, "state", `vector-memory:${key}`, name, { surfaces: reqSurf("state") });
      } else addReq(W, "vector", shortType(d.baseType), name, { surfaces: reqSurf("vector") });
      break;
    case "code": {
      const src = allStrings(d.params).join("\n");
      const m = src.match(/getWorkflowStaticData\s*\(\s*['"`](\w+)['"`]/);
      if (/getWorkflowStaticData/.test(src)) {
        const scope = m ? m[1] : "global";
        addShared(W, "static-data", `scope ${scope}`, name);
        addReq(W, "state", `static-data:${scope}`, name, { surfaces: reqSurf("state") });
      }
      break;
    }
    case "subworkflow":
      W.calls.push({ node: name, br, d });
      break;
  }
  // A step that calls the person's n8n instance back (the n8n node's reads): the report says it
  // works only while n8n keeps running (renderText note, MIGRATION.md).
  if (d.flags.includes("calls-n8n")) addReq(W, "http", "n8n instance", name, { surfaces: reqSurf("http"), note: N8N_STAYS_NOTE });
  const extra = own(caps.nodeRequirements, d.baseType);
  if (extra) addReq(W, extra, extra === "host-disk" ? "n8n host disk" : extra, name, { surfaces: reqSurf(extra) });
  if (d.secrets === true) {
    const proto = d.kind === "db" ? "secret:db" : "secret:http";
    const creds = credentialNames(d);
    if (!creds.length) addReq(W, "secret", `${shortType(d.baseType)} (no credential named in the export)`, name, { surfaces: reqSurf(proto) });
    for (const c of creds) addReq(W, "secret", c.name, name, { surfaces: reqSurf(proto) });
  }
}

// First pass: everything that needs only this workflow.
function analyzeLocal(item, ctx, parent = null, prefix = "") {
  const W = newWorkflow(item, ctx, parent, prefix);
  computeBranches(W);
  for (const n of W.duplicates) addBlocker(W, "input-incomplete", `more than one node is named "${n}", so the connections are ambiguous`, n);
  const { infos, order } = W;
  W.disabled = order.filter((n) => infos.get(n).disabled && infos.get(n).role !== "annotation");
  W.triggers = order
    .map((n) => infos.get(n))
    .filter((d) => !d.disabled && d.isTrigger && d.role === "trigger")
    .map((d) => ({ name: d.name, kind: d.wakeup ?? "endpoint", d }));
  for (const n of order) {
    const d = infos.get(n);
    if (d.disabled || d.role === "annotation") continue;
    processNode(W, d, ctx, W.branch.get(n));
  }
  for (const n of order) {
    const d = infos.get(n);
    if (!d.disabled && d.status !== "mapped") W.unmapped.push({ node: n, type: d.type, typeVersion: d.typeVersion, reason: d.status, branch: publicBranch(W.branch.get(n)) });
  }
  // Inline secrets: every string parameter of every node (notes and disabled
  // nodes included: a leaked key is a leak wherever it sits) and pinData.
  W.inlineSecrets = [];
  for (const n of order) {
    const d = infos.get(n);
    for (const s of scanSecrets(d.params, "parameters")) {
      W.inlineSecrets.push({ node: n, ...s });
      const br = W.branch.get(n);
      if (!d.disabled && d.role !== "annotation" && !d.llmApi && (br === "main" || br === "error-output")) addReq(W, "secret", `inline:${s.kind}`, n, { surfaces: surfacesFrom(ctx.capabilities.requirements?.["secret:http"]) });
    }
  }
  if (isObj(W.wf.pinData)) for (const [n, v] of Object.entries(W.wf.pinData)) for (const s of scanSecrets(v, `pinData.${n}`)) W.inlineSecrets.push({ node: n, ...s });
  W.credentials = [];
  for (const n of order) {
    const d = infos.get(n);
    if (d.disabled) continue;
    for (const c of credentialNames(d)) {
      let e = W.credentials.find((x) => x.type === c.type && x.name === c.name);
      if (!e) W.credentials.push((e = { type: c.type, name: c.name, nodes: [] }));
      e.nodes.push(n);
    }
  }
  W.credentials.sort((a, b) => a.type.localeCompare(b.type) || a.name.localeCompare(b.name));
  return W;
}

const publicBranch = (b) => (b === "error-output" || b === "error-trigger" ? "error" : b);

// ---------- sub-workflows ----------

function readCallTarget(d) {
  const p = d.params;
  const source = p.source ?? "database";
  if (source === "parameter") return { status: "inline", json: p.workflowJson };
  if (source === "localFile") return { status: "file" };
  if (source === "url") return { status: "url" };
  const { value, cached } = rlValue(p.workflowId);
  if (value === undefined || value === null || txt(value).trim() === "") return { status: "empty" };
  let v = txt(value);
  if (isExpr(v)) {
    if (v.replace(/[={}\s]/g, "") === "$workflow.id") return { status: "self" };
    return { status: "expression" };
  }
  if (isObj(p.workflowId) && p.workflowId.mode === "url") {
    const m = v.match(/workflow\/([^/?#]+)/);
    if (m) v = m[1];
  }
  return { status: "id", id: v, cached: typeof cached === "string" && cached && !isExpr(cached) ? cached : null };
}

// Second pass: links every call to its target workflow, asks about ids the
// run does not hold, and analyses inline sub-workflows.
function resolveCalls(W, ctx) {
  const kindFor = (br, kind) => (br === "main" ? kind : "dropped-branch");
  const reasonFor = (br, reason) => (br === "main" ? reason : `only on an error branch: ${reason}`);
  W.callInfo = [];
  for (const call of W.calls) {
    const t = readCallTarget(call.d);
    const info = { node: call.node, status: t.status, target: null };
    W.callInfo.push(info);
    const fail = (reason, missing) => {
      addBlocker(W, kindFor(call.br, "input-incomplete"), reasonFor(call.br, reason), call.node);
      if (missing && call.br === "main") addReq(W, "missing-export", missing, call.node, { surfaces: surfacesFrom(ctx.capabilities.requirements?.["missing-export"]) });
    };
    if (t.status === "self" || (t.status === "id" && t.id === W.id)) {
      info.status = "self";
      info.target = W.parent ? W.parent.id : W.id;
      addShared(W, "self-call", "this workflow", call.node);
      continue;
    }
    if (t.status === "id") {
      let target = ctx.byId.get(t.id);
      if (!target) {
        const cand = t.cached ? ctx.items.find((x) => x.name === t.cached && x.id !== W.id) : null;
        const label = `"${t.id}"${t.cached ? ` ("${t.cached}")` : ""}`;
        // A workflow with an Execute Workflow Trigger of its own may be calling
        // itself (or a sub-flow pasted on the same canvas) by an id it had
        // elsewhere: offer "self".
        const owner = W.parent || W;
        const selfOk = !W.parent && W.triggers.some((x) => x.kind === "subworkflow");
        const options = cand ? { true: `use workflow "${cand.id}"` } : {};
        if (selfOk) options.self = "this workflow itself";
        Object.assign(options, { false: "keep it missing", "<workflow id>": "use that workflow" });
        const { value: v } = ask(W, ctx, "subworkflow-id", call.node, {
          text: cand
            ? `Is workflow id ${label}, called by "${call.node}", the workflow "${t.cached}" that this export holds as id "${cand.id}"?`
            : `Which workflow is id ${label}, called by "${call.node}"? It is not in this export. Answer ${selfOk ? "self (this workflow has its own Execute Workflow Trigger), " : ""}the id of a workflow in the export, or false if it is missing.`,
          affects: "sub-workflow",
          answerType: "text",
          options,
          assumed: "false",
        });
        if (v === "self" && selfOk) {
          info.status = "self";
          info.target = owner.id;
          addShared(W, "self-call", "this workflow", call.node);
          continue;
        }
        if (v === "true" && cand) target = ctx.byId.get(cand.id);
        else if (v !== "false" && v !== "true") target = ctx.byId.get(v);
        if (target) info.status = "id-answered";
      }
      if (!target) {
        info.status = "missing";
        fail(`sub-workflow ${`"${t.id}"`}${t.cached ? ` ("${t.cached}")` : ""} is not in the export`, `workflow ${t.id}${t.cached ? ` (${t.cached})` : ""}`);
        continue;
      }
      if (target.id === W.id) {
        info.status = "self";
        info.target = W.id;
        addShared(W, "self-call", "this workflow", call.node);
        continue;
      }
      info.target = target.id;
      call.target = target;
      continue;
    }
    if (t.status === "inline") {
      let parsed = null;
      // The JSON holds n8n expressions of its own, so only a leading "=" makes
      // the whole parameter an expression.
      if (typeof t.json === "string" && !t.json.startsWith("=")) {
        try {
          parsed = unwrap(JSON.parse(t.json), `${W.id}#${call.node}`);
        } catch {
          parsed = null;
        }
      } else if (isObj(t.json)) parsed = unwrap(t.json, `${W.id}#${call.node}`);
      if (!parsed) {
        fail("the inline sub-workflow JSON cannot be read");
        continue;
      }
      const owner = W.parent || W;
      const sub = analyzeLocal({ ...parsed[0], id: `${W.id}#${call.node}`, name: `${call.node} (inline)`, file: W.file }, ctx, owner, `${W.prefix}${call.node} › `);
      ctx.pseudo.push(sub);
      // The top workflow lists the inline sub-workflow's credentials, by path.
      for (const c of sub.credentials) {
        let e = owner.credentials.find((x) => x.type === c.type && x.name === c.name);
        if (!e) owner.credentials.push((e = { type: c.type, name: c.name, nodes: [] }));
        for (const n of c.nodes) e.nodes.push(`${sub.prefix}${n}`);
      }
      owner.credentials.sort((a, b) => a.type.localeCompare(b.type) || a.name.localeCompare(b.name));
      resolveCalls(sub, ctx);
      info.target = null;
      call.target = sub;
      continue;
    }
    const reasons = {
      // The id is picked at run time among the workflows in n8n, which stay there: the public API
      // (v1) has no endpoint that runs a workflow, so no call back to n8n can stand in for it.
      expression: "the sub-workflow id is set by an expression, so the workflow it runs is picked at run time from the ones in n8n; n8n's public API has no endpoint that runs a workflow",
      empty: "the sub-workflow id is empty",
      file: "the sub-workflow is read from a file on the n8n host",
      url: "the sub-workflow is fetched from a URL at run time",
    };
    fail(reasons[t.status]);
  }
}

// Third pass: a caller takes over what its callees need (transitively, once
// per callee): blocking and substitution blockers, requirements and model
// steps, attributed to the caller's own call node.
function propagate(W) {
  // A callee's own wake-up (relay, poll, schedule speed) is not the caller's.
  const SKIP = new Set(["relay", "poll", "frequency-change"]);
  const visit = (X, top, seen) => {
    for (const call of X.calls) {
      const C = call.target;
      if (!C || seen.has(C) || C === W) continue;
      seen.add(C);
      const t = top ?? call;
      if (!C.parent) C.calledBy.add(W.parent ? W.parent.id : W.id);
      for (const b of C.own.blockers) {
        if (!BLOCKING.has(b.kind) && b.kind !== "substitution") continue;
        const reason = `sub-workflow "${C.name}": ${b.reason}`;
        if (t.br === "main") addBlocker(W, b.kind, reason, t.node);
        else addBlocker(W, "dropped-branch", `only on an error branch: ${reason}`, t.node);
      }
      for (const r of C.own.req) if (!SKIP.has(r.kind)) addReq(W, r.kind, r.name, t.node, { surfaces: r.surfaces, ops: r.ops, creds: r.creds });
      for (const l of C.own.levers) W.levers.add(l);
      if (C.own.hasModel) W.callModelNodes.add(t.node);
      visit(C, t, seen);
    }
  };
  visit(W, null, new Set([W]));
}

function snapshotOwn(W) {
  const steps = W.order.map((n) => W.infos.get(n)).filter((d) => !d.disabled && W.branch.get(d.name) === "main");
  W.own = {
    blockers: [...W.blockers.values()].map((b) => ({ ...b })),
    req: [...W.req.values()].map((r) => ({ ...r, nodes: new Set(r.nodes), ops: [...r.ops], creds: r.creds && [...r.creds] })),
    levers: [...W.levers],
    hasModel: steps.some((d) => MODEL_KINDS.has(d.kind) && d.role === "step"),
  };
}

// ---------- body, schedule, outcome ----------

function computeBody(W) {
  const considered = W.order
    .map((n) => W.infos.get(n))
    .filter((d) => !d.disabled && W.branch.get(d.name) === "main" && !d.isTrigger && d.role !== "annotation" && d.role !== "subnode" && !NEUTRAL_STEP_TYPES.has(d.type));
  const models = considered.filter((d) => d.status === "mapped" && MODEL_KINDS.has(d.kind)).map((d) => d.name);
  const callModels = [...W.callModelNodes].filter((n) => W.branch.get(n) === "main");
  const disq = considered.filter((d) => d.status !== "mapped" || !PROMPT_KINDS.has(d.kind)).map((d) => d.name);
  const hasModel = models.length > 0 || callModels.length > 0;
  if (!hasModel) return { kind: "script", decidedBy: [] };
  if (!disq.length) return { kind: "prompt", decidedBy: models };
  const set = new Set([...models, ...callModels, ...disq]);
  return { kind: "script+model", decidedBy: W.order.filter((n) => set.has(n)) };
}

// Whether a timezone moves its clocks during the year of nowMs: its UTC offset
// on 1 January and 1 July differ. An unknown name gives false.
export function observesDst(tz, nowMs) {
  try {
    const f = new Intl.DateTimeFormat("en-US", { timeZone: tz, timeZoneName: "longOffset" });
    const off = (ms) => f.formatToParts(ms).find((p) => p.type === "timeZoneName")?.value;
    const y = new Date(nowMs).getUTCFullYear();
    return off(Date.UTC(y, 0, 1)) !== off(Date.UTC(y, 6, 1));
  } catch {
    return false;
  }
}

function computeSchedule(W, ctx) {
  const tz = typeof W.settings.timezone === "string" && W.settings.timezone && W.settings.timezone !== "DEFAULT" ? W.settings.timezone : null;
  const time = W.triggers.filter((t) => t.kind === "schedule" || t.kind === "poll");
  const out = { runsPerDay: null, shortestIntervalSec: null, fits: "n/a", timezone: tz ?? N8N_DEFAULT_TIMEZONE, timezoneSource: tz ? "workflow" : "n8n-default" };
  if (!time.length) return out;
  if (!tz && time.some((t) => timeOfDayMatters(t.d))) {
    const a = ask(W, ctx, "timezone", null, {
      text: `Which timezone does the schedule of "${W.name}" run in? The export does not say; n8n's default is ${N8N_DEFAULT_TIMEZONE} unless GENERIC_TIMEZONE is set.`,
      affects: "timezone",
      answerType: "text",
      options: { "<IANA timezone>": "schedule.timezone" },
      assumed: N8N_DEFAULT_TIMEZONE,
    });
    if (a.answered) (out.timezone = a.value), (out.timezoneSource = "answer");
  }
  // The run counts below ignore DST. A time-of-day run in a zone that moves
  // its clocks can shift by an hour, be skipped or repeat around the change.
  if (time.some((t) => timeOfDayMatters(t.d)) && observesDst(out.timezone, ctx.now)) out.dstNote = true;
  const crons = [];
  const fixed = [];
  let unknown = false;
  for (const t of time) {
    const r = triggerTimes(t.d);
    if (r.error) {
      const { value: v } = ask(W, ctx, "interval", t.name, {
        text: `How often does "${t.name}" fire, in seconds? Its schedule cannot be read (${r.error}).`,
        affects: "schedule",
        answerType: "text",
        options: { "<seconds>": "shortest interval" },
        assumed: null,
      });
      const sec = Number(v);
      if (v != null && sec > 0) fixed.push({ runsPerDay: 86400 / sec, shortestSec: sec });
      else unknown = true;
      continue;
    }
    crons.push(...r.crons);
    fixed.push(...r.fixed);
  }
  let runs = fixed.reduce((a, f) => a + f.runsPerDay, 0);
  let shortest = fixed.length ? Math.min(...fixed.map((f) => f.shortestSec)) : null;
  if (crons.length) {
    const sim = simulateCron(crons, ctx.now);
    runs += sim.runsPerDay;
    if (sim.shortestSec != null) shortest = shortest == null ? sim.shortestSec : Math.min(shortest, sim.shortestSec);
  }
  const th = ctx.thresholds;
  out.runsPerDay = unknown && !fixed.length && !crons.length ? null : round(runs);
  out.shortestIntervalSec = shortest == null ? null : Math.round(shortest);
  if (unknown && out.shortestIntervalSec == null) out.fits = "local-task";
  else if (out.shortestIntervalSec == null || out.shortestIntervalSec >= th.cloudMinIntervalSec) out.fits = "cloud-task";
  else if (out.shortestIntervalSec >= th.localMinIntervalSec) out.fits = "local-task";
  else out.fits = "frequency-change";
  if (out.fits === "frequency-change") {
    const name = `every ${formatDuration(out.shortestIntervalSec)} → at least every ${formatDuration(th.localMinIntervalSec)}`;
    for (const t of time) addReq(W, "frequency-change", name, t.name, { surfaces: surfacesFrom(ctx.capabilities.requirements?.["frequency-change"]) });
  }
  return out;
}

// Nodes on the way from a trigger to its reply. For a webhook replying with a
// Respond to Webhook node: the nodes that lead to one; otherwise everything
// the trigger reaches. Sub-nodes attached on the way count.
function pathNodes(W, trig) {
  const all = reach([trig], W.graph, W.infos, true);
  const d = W.infos.get(trig);
  let set = all;
  if (d.params.responseMode === "responseNode") {
    const responders = [...all].filter((n) => W.infos.get(n).type === RESPOND_TYPE);
    if (responders.length) {
      const back = new Map();
      for (const [src, outs] of W.graph.mainOut) for (const list of outs) for (const t of list) (back.get(t) || back.set(t, []).get(t)).push(src);
      const leads = new Set(responders);
      const q = [...responders];
      while (q.length) for (const s of back.get(q.shift()) || []) if (all.has(s) && !leads.has(s)) leads.add(s), q.push(s);
      set = leads;
    }
  }
  return withSubnodes(set, W.graph);
}

function modelOnPath(W, trig) {
  for (const n of pathNodes(W, trig)) {
    const d = W.infos.get(n);
    if (d.disabled) continue;
    if (d.status === "mapped" && MODEL_KINDS.has(d.kind)) return true;
    if (W.callModelNodes.has(n)) return true;
  }
  return false;
}

function triggerNodes(W, kind) {
  return W.triggers.filter((t) => t.kind === kind);
}

// Chat apps for the chat-app-users question. poll: the provider has an API to
// fetch new messages, so an owner-only bot can run in a local task without
// its webhook. WhatsApp, Twilio, Slack and Discord bots are offered no poll
// lever: WhatsApp and Twilio have no polling API, and the other two are not
// mapped here yet.
const CHAT_APPS = {
  telegram: { label: "Telegram", poll: true, pollName: "Telegram getUpdates", pollNote: "getUpdates returns nothing while the bot has a webhook: call deleteWebhook first, and stop the n8n workflow that listens" },
  whatsapp: { label: "WhatsApp", poll: false },
  twilio: { label: "Twilio SMS", poll: false },
  slack: { label: "Slack", poll: false },
  discord: { label: "Discord", poll: false },
};
const CHAT_TRIGGERS = { "n8n-nodes-base.telegramTrigger": "telegram", "n8n-nodes-base.whatsAppTrigger": "whatsapp", "n8n-nodes-base.twilioTrigger": "twilio" };
// Messaging nodes and the parameters that name who gets the message.
const CHAT_SENDERS = {
  "n8n-nodes-base.telegram": ["telegram", ["chatId"]],
  "n8n-nodes-base.whatsApp": ["whatsapp", ["recipientPhoneNumber"]],
  "n8n-nodes-base.twilio": ["twilio", ["to"]],
  "n8n-nodes-base.slack": ["slack", ["channelId", "channel", "user"]],
  "n8n-nodes-base.discord": ["discord", ["channelId", "userId"]],
};
const reEscape = (x) => x.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");

// {provider, via} when a relay trigger is a chat app: a chat-app trigger
// (mapping flag chat-app), or a plain Webhook trigger whose steps reply
// through a messaging node to a recipient taken from the webhook's own data.
// The webhook rule is conservative: the send must be a write on the main
// path from that webhook, and its recipient parameter an expression that
// reads the request body or query, through $json or the webhook node by
// name, at a chat-like key (chat, from, sender, recipient, channel, user,
// wa_id, contacts, phone). A fixed chat id, a value computed elsewhere, or an
// HTTP Request to a bot API does not count.
function chatAppOf(W, t) {
  if (t.d.flags.includes("chat-app")) return { provider: CHAT_TRIGGERS[t.d.baseType] ?? "telegram", via: null };
  if (t.d.baseType !== "n8n-nodes-base.webhook") return null;
  const name = reEscape(t.name);
  const src = `(?:\\$json|\\$\\(\\s*['"\`]${name}['"\`]\\s*\\)\\s*\\.\\s*(?:item|first\\(\\s*\\)|last\\(\\s*\\)|all\\(\\s*\\)\\s*\\[\\s*\\d+\\s*\\])\\s*\\.\\s*json|\\$node\\[\\s*['"\`]${name}['"\`]\\s*\\]\\s*\\.\\s*json)`;
  const re = new RegExp(`${src}\\s*(?:\\.\\s*(?:body|query)\\b|\\[\\s*['"](?:body|query)['"]\\s*\\])[\\w.$[\\]'"\\s()]*?\\b(?:chat|from|sender|recipient|channel|user|wa_id|contacts|phone)\\b`, "i");
  for (const n of reach([t.name], W.graph, W.infos, true)) {
    const d = W.infos.get(n);
    const sender = own(CHAT_SENDERS, d.baseType);
    if (!sender || d.disabled || d.status !== "mapped" || d.effect !== "write") continue;
    const [provider, params] = sender;
    const vals = params.flatMap((p) => allStrings(rlValue(d.params[p]).value));
    if (vals.some((v) => isExpr(v) && re.test(v))) return { provider, via: d.name };
  }
  return null;
}

// What an artifact cannot do for these requirements. An artifact page has no
// backend: its fetch reaches only its own origin (CHECKS.md), so http, stored
// secrets, the bundled server and the n8n host's disk are "no" there, and
// connectors work only through its mcp capability (needs:artifact-mcp).
// Returns {no, needs}: requirements that are no on the artifact, and those
// that need setup first (mcp, sample, db, a connector operation check).
//
// The two run-on-request targets read it differently, on purpose:
// - manual (and an uncalled sub-workflow) goes to an artifact only when
//   nothing is missing at all, because a skill is an equal alternative and
//   needs no setup;
// - a form has no such alternative: the form itself always lives in the
//   artifact. Its steps run there too unless one is no on the artifact; then
//   the artifact collects the submission and a task runs the steps
//   (requirement task-handoff).
function artifactGaps(reqs) {
  const steps = reqs.filter((r) => r.kind !== "task-handoff");
  return { no: steps.filter((r) => (r.surfaces?.artifact ?? "no") === "no"), needs: steps.filter((r) => r.surfaces?.artifact?.startsWith("needs:")) };
}
// What an artifact lacks, by name: the thing a needs: value waits for, or the
// requirement kind it cannot have at all (a connector operation with no tool:
// that app's REST API; a substitution: what it substitutes in). The bundled
// server only follows from the others.
const lackNames = (rs) => {
  const names = uniq(rs.map((r) => (r.surfaces?.artifact?.startsWith("needs:") ? r.surfaces.artifact.slice(6) : r.kind === "connector" && r.noTool?.length ? `the ${r.name} REST API` : r.kind === "substitution" ? `the ${r.name.split(" → ").at(-1)}` : r.kind)));
  return names.length > 1 ? names.filter((n) => n !== "bundled-server") : names;
};

function outcomeForKind(W, ctx, k) {
  const reqs = [...W.req.values()];
  let o;
  // A relay outcome: each pushed event is one fire of the cloud task's API
  // trigger. The relay requirements get the trigger's limits as a note, and,
  // since nothing in an export says how many events arrive, one question asks
  // the peak rate (assumed under the per-task cap). Over the per-account cap
  // the workflow stays in n8n. Not asked for a bot only its owner messages,
  // nor when a blocker keeps the workflow in n8n anyway.
  const relayVolume = (nodes, ask_ = true) => {
    const perTask = ctx.thresholds.apiTriggerFiresPerTaskHour;
    const perAccount = ctx.thresholds.apiTriggerFiresPerAccountHour;
    // Already staying in n8n for another reason: the rate changes nothing.
    if (!perTask || !perAccount || [...W.blockers.values()].some((b) => BLOCKING.has(b.kind))) return null;
    for (const r of W.req.values()) if (r.kind === "relay" && !r.note) r.note = `the cloud task's API trigger takes at most ${perTask} fires per task and ${perAccount} per account an hour, shared with Run now`;
    if (!ask_) return null;
    const { value: v } = ask(W, ctx, "event-volume", null, {
      text: `How many events an hour reach ${nodes.map((n) => `"${n}"`).join(", ")} at peak? Each one fires the cloud task's API trigger, which takes at most ${perTask} an hour per task and ${perAccount} per account.`,
      nodes,
      affects: "outcome",
      answerType: "choice",
      options: { [`under-${perTask}`]: "subscription:cloud-task", [`${perTask}-${perAccount}`]: "subscription:cloud-task (the forwarder batches events or spreads them over several tasks)", [`over-${perAccount}`]: "keep-in-n8n (event volume over the API trigger cap)" },
      assumed: `under-${perTask}`,
    });
    if (v === `over-${perAccount}`) for (const n of nodes) addBlocker(W, "unsupported", "event volume over the API trigger cap", n);
    return v === `${perTask}-${perAccount}` ? `; over ${perTask} events an hour, the forwarder batches them or spreads them over several tasks (at most ${perAccount} an hour per account)` : "";
  };
  if (k === "endpoint") {
    let outsiders = false;
    let key = false;
    for (const t of triggerNodes(W, "endpoint")) {
      const tk = modelOnPath(W, t.name) ? "key" : "no-key";
      const { value: v } = ask(W, ctx, "endpoint-callers", t.name, {
        text: `Who calls the URL of "${t.name}" and waits for its reply: outsiders (other people or systems), or only you, from Claude?`,
        affects: "outcome",
        answerType: "choice",
        options: { outsiders: `hosted:${tk}`, "only-me": "subscription:skill" },
        assumed: "outsiders",
      });
      if (v !== "only-me") outsiders = true;
      if (v !== "only-me" && tk === "key") key = true;
    }
    o = outsiders
      ? { kind: "hosted", target: key ? "key" : "no-key", reason: key ? "an outside caller waits for a reply that a model writes" : "an outside caller waits for a reply; no model step on the way" }
      : { kind: "subscription", target: "skill", reason: "only you call this URL, from Claude: a skill replaces it" };
  } else if (k === "mcp-server") {
    let onlyClaude = true;
    let key = false;
    for (const t of triggerNodes(W, "mcp-server")) {
      const { value: v } = ask(W, ctx, "mcp-only-client", t.name, {
        text: `Is Claude the only client that uses the MCP server of "${t.name}"?`,
        affects: "outcome",
        answerType: "boolean",
        options: { true: "replaced", false: `hosted:${modelOnPath(W, t.name) ? "key" : "no-key"}` },
        assumed: true,
      });
      if (v === false) onlyClaude = false;
      if (modelOnPath(W, t.name)) key = true;
    }
    o = onlyClaude
      ? { kind: "replaced", target: null, reason: "n8n serves tools to Claude: Claude's own connectors and skills replace it" }
      : { kind: "hosted", target: key ? "key" : "no-key", reason: "other MCP clients use this server" };
  } else if (k === "chat") {
    let outsiders = false;
    for (const t of triggerNodes(W, "chat")) {
      if (!t.d.flags.includes("public-chat-page")) continue;
      const { value: v } = ask(W, ctx, "chat-outsiders", t.name, {
        text: `Do people outside your organisation use the public chat page of "${t.name}"?`,
        affects: "outcome",
        answerType: "boolean",
        options: { true: "hosted:key", false: "subscription:skill" },
        assumed: false,
      });
      if (v === true) outsiders = true;
    }
    o = outsiders ? { kind: "hosted", target: "key", reason: "outsiders chat with a model through a public page" } : { kind: "subscription", target: "skill", reason: "the chat trigger becomes a skill" };
  } else if (k === "form") {
    o = { kind: "subscription", target: "artifact-form", reason: "the form trigger becomes an artifact form for people in your organisation; its steps run in the artifact" };
    for (const t of triggerNodes(W, "form")) {
      if (!t.d.flags.includes("public-form")) continue;
      const waits = t.d.flags.includes("form-waits-for-result");
      const tk = modelOnPath(W, t.name) ? "key" : "no-key";
      const { value: v } = ask(W, ctx, "form-outsiders", t.name, {
        text: `Do people outside your organisation fill in the form "${t.name}"? It needs no sign-in.`,
        affects: "outcome",
        answerType: "boolean",
        options: { true: waits ? `hosted:${tk}` : "subscription:cloud-task (with a relay)", false: "subscription:artifact-form" },
        assumed: false,
      });
      if (v === true) {
        if (waits) o = { kind: "hosted", target: tk, reason: "outsiders fill the form and wait for its result" };
        else {
          o = { kind: "subscription", target: "cloud-task", reason: "outsiders fill the form; a hosted form page relays each submission to a cloud task" };
          addReq(W, "relay", "form page", t.name, { surfaces: surfacesFrom(ctx.capabilities.requirements?.relay) });
          o.reason += relayVolume([t.name]) ?? "";
        }
        break;
      }
    }
    // The form stays in the artifact; a step the artifact cannot run sends
    // every step to a task, which picks submissions up from the artifact.
    const gaps = artifactGaps(reqs);
    if (o.target === "artifact-form" && gaps.no.length) {
      const task = reqs.every((r) => r.surfaces?.cloudTask !== "no") ? "cloud-task" : reqs.every((r) => r.surfaces?.localTask !== "no") ? "local-task" : "cloud-task";
      const forms = triggerNodes(W, "form");
      const waits = forms.some((t) => t.d.flags.includes("form-waits-for-result"));
      for (const t of forms) addReq(W, "task-handoff", task, t.name, { surfaces: surfacesFrom(ctx.capabilities.requirements?.["task-handoff"]) });
      o.reason = `the form collects submissions in an artifact; an artifact lacks ${lackNames(gaps.no).join(", ")}, so a ${TARGET_LABEL[task]} picks each submission up and runs the steps${waits ? "; the form can no longer show the result, the task delivers it later" : ""}`;
    }
  } else if (k === "relay") {
    const cap = ctx.thresholds.apiTriggerFiresPerTaskHour;
    const relayReason = `an event is pushed in with no reply expected: a forwarder posts it to the cloud task's API trigger${cap ? ` (at most ${cap} events an hour)` : ""}`;
    o = { kind: "subscription", target: "cloud-task", reason: relayReason };
    // A chat app (a Telegram, WhatsApp or SMS trigger, or a plain webhook
    // whose steps reply to the chat named in its body) is a conversation:
    // someone usually waits for each reply, which a cloud task cannot promise.
    const answers = [];
    let others = false;
    for (const t of triggerNodes(W, "relay")) {
      const chat = chatAppOf(W, t);
      if (!chat) {
        others = true;
        continue;
      }
      const tk = modelOnPath(W, t.name) ? "key" : "no-key";
      const app = CHAT_APPS[chat.provider];
      const { value: v } = ask(W, ctx, "chat-app-users", t.name, {
        text: `${chat.via ? `"${t.name}" is a plain webhook, but "${chat.via}" replies to the ${app.label} chat named in its body. ` : ""}Who messages "${t.name}" and waits for the replies: outsiders (customers, other people), only you, or nobody waits? A cloud task's start-up time is not measured yet${cap ? ` and its API trigger takes at most ${cap} events an hour` : ""}.`,
        affects: "outcome",
        answerType: "choice",
        options: {
          outsiders: `hosted:${tk}`,
          "only-me": app.poll ? `subscription:local-task (polls ${app.label} every minute)` : `subscription:cloud-task (${app.label} has no polling API, so a relay)`,
          "in-claude": "subscription:skill (you message Claude instead of the bot)",
          "no-reply": "subscription:cloud-task",
        },
        assumed: "outsiders",
      });
      answers.push({ v, tk, t, app });
    }
    const out = answers.filter((a) => a.v === "outsiders");
    const all = (f) => answers.length > 0 && !others && answers.every(f);
    const labels = uniq(answers.map((a) => a.app.label)).join(" and ");
    // The bot's webhook is no longer needed once nothing is relayed.
    const dropRelay = () => {
      const names = answers.map((a) => a.t.name);
      for (const [key, r] of W.req) if (r.kind === "relay" && [...r.nodes].every((n) => names.includes(n))) W.req.delete(key);
    };
    if (out.length) {
      const key = out.some((a) => a.tk === "key");
      o = { kind: "hosted", target: key ? "key" : "no-key", reason: `people wait in a chat app for each reply${key ? ", which a model writes" : ""}` };
    } else if (all((a) => a.v === "in-claude")) {
      dropRelay();
      o = { kind: "subscription", target: "skill", reason: `only you message this ${labels} bot, and you will message Claude instead: a skill replaces it` };
    } else if (all((a) => a.v === "only-me" && a.app.poll)) {
      // Owner-only bot on a provider with a polling API (Telegram getUpdates):
      // a local task polls every minute instead of receiving the webhook.
      const every = formatDuration(ctx.thresholds.localMinIntervalSec);
      const within = ctx.thresholds.localMinIntervalSec === 60 ? "a minute" : every;
      for (const a of answers) {
        addReq(W, "poll", a.app.pollName, a.t.name, { surfaces: surfacesFrom(ctx.capabilities.requirements?.poll), note: a.app.pollNote });
        addReq(W, "frequency", `every ${every}`, a.t.name, {
          surfaces: surfacesFrom(ctx.capabilities.requirements?.frequency),
          note: `replies arrive within about ${within}, only while your computer is on and Claude is open: ${Math.round(86400 / ctx.thresholds.localMinIntervalSec)} task runs a day`,
        });
      }
      dropRelay();
      W.levers.add("poll");
      o = { kind: "subscription", target: "local-task", reason: `only you message this ${labels} bot: a local task polls ${answers[0].app.pollName} every ${every} instead of the webhook, so replies arrive within about ${within} while your computer is on` };
    } else {
      const relayOnly = answers.filter((a) => a.v === "only-me" && !a.app.poll);
      if (relayOnly.length) {
        const which = uniq(relayOnly.map((a) => a.app.label)).join(" and ");
        o.reason = `only you message this ${which} bot, but ${which} has no polling API: a forwarder posts each message to the cloud task's API trigger${cap ? ` (at most ${cap} an hour)` : ""} and each reply waits for a task to start; or keep it in n8n`;
      }
      const ownerOnly = answers.length > 0 && !others && answers.every((a) => a.v === "only-me");
      o.reason += relayVolume(triggerNodes(W, "relay").map((t) => t.name), !ownerOnly) ?? "";
    }
  } else if (k === "schedule" || k === "poll") {
    const s = W.schedule;
    const what = `${k === "poll" ? "polls" : "fires"} ${intervalLabel(s)}`;
    const cloudMin = formatDuration(ctx.thresholds.cloudMinIntervalSec);
    const localMin = formatDuration(ctx.thresholds.localMinIntervalSec);
    if (s.fits === "cloud-task") o = { kind: "subscription", target: "cloud-task", reason: `${what}, within a cloud task's limit of one run per ${cloudMin}` };
    else if (s.fits === "local-task") o = { kind: "subscription", target: "local-task", reason: `${what}, more often than a cloud task's one run per ${cloudMin}, so a local task` };
    else o = { kind: "subscription", target: "local-task", reason: `${what}, more often than a local task's one run per ${localMin}: the schedule must slow down` };
  } else if (k === "error") {
    o = { kind: "keep-in-n8n", target: null, reason: "an error workflow stays with the workflows that remain in n8n; moved ones get the runner's failure alert instead" };
  } else {
    // Run on request. An artifact only when it can do every step today;
    // otherwise a skill, run in Claude Code or Cowork where secrets and the
    // bundled server are available.
    const what = k === "subworkflow" ? "a sub-workflow with no caller in this export, run on request" : "run by hand";
    const gaps = artifactGaps(reqs);
    const notOk = reqs.filter((r) => gaps.no.includes(r) || gaps.needs.includes(r));
    if (!notOk.length) o = { kind: "subscription", target: "artifact", reason: `${what}: the artifact's Run now button` };
    else o = { kind: "subscription", target: "skill", reason: `${what}, so a skill in Claude Code or Cowork; an artifact lacks ${lackNames(notOk).join(", ")}` };
  }
  if (o.kind === "subscription" && o.target === "cloud-task") {
    const noCloud = reqs.filter((r) => r.surfaces?.cloudTask === "no");
    if (noCloud.length && reqs.every((r) => r.surfaces?.localTask !== "no")) {
      o.target = "local-task";
      // A site on a local address is out of the cloud VM's reach; anything else cannot run there.
      const local = uniq(noCloud.filter((r) => r.kind === "local-network").map((r) => r.name));
      const other = uniq(noCloud.filter((r) => r.kind !== "local-network").map((r) => r.name));
      const why = [...(other.length ? [`${other.join(", ")} cannot run in a cloud task`] : []), ...(local.length ? [`${local.join(", ")} ${local.length > 1 ? "are local addresses" : "is a local address"} a cloud task cannot reach`] : [])];
      o.reason += `; ${why.join("; ")}, so a local task`;
    }
  }
  return o;
}

// Wake-up kinds that never get a target of their own beside another trigger:
// a manual trigger there is for testing, a sub-workflow trigger is a
// self-call, an error trigger is a dropped branch.
const NO_ALSO_TARGET = new Set(["manual", "subworkflow", "error"]);

// The deciding wake-up gives the outcome. Every other trigger kind that would
// need a different target is listed in alsoTargets (for example a chat
// trigger beside a schedule: a skill plus a cloud task).
function decideOutcome(W, ctx) {
  const o = outcomeForKind(W, ctx, W.wakeup.kind);
  o.alsoTargets = [];
  for (const k of W.wakeup.all) {
    if (k === W.wakeup.kind || NO_ALSO_TARGET.has(k)) continue;
    const x = outcomeForKind(W, ctx, k);
    if (x.kind !== o.kind || x.target !== o.target) o.alsoTargets.push({ wakeup: k, kind: x.kind, target: x.target, nodes: triggerNodes(W, k).map((t) => t.name) });
  }
  const blocking = [...W.blockers.values()].filter((b) => BLOCKING.has(b.kind));
  if (blocking.length) return { kind: "keep-in-n8n", target: null, reason: blocking.map((b) => b.reason).join("; "), alsoTargets: [] };
  return o;
}

export function intervalLabel(s) {
  if (s.shortestIntervalSec == null) return s.runsPerDay == null ? "on an unknown schedule" : `${round(s.runsPerDay, 3)} times a day`;
  const regular = s.runsPerDay != null && Math.abs(s.runsPerDay * s.shortestIntervalSec - 86400) < 1;
  return regular ? `every ${formatDuration(s.shortestIntervalSec)}` : `${round(s.runsPerDay, 2)} times a day, at least ${formatDuration(s.shortestIntervalSec)} apart`;
}

function computeWakeup(W) {
  const kinds = uniq(W.triggers.map((t) => t.kind)).sort(byOrder(WAKEUP_RANK));
  const kind = kinds[0] ?? "manual";
  return { kind, nodes: W.triggers.filter((t) => t.kind === kind).map((t) => t.name), all: kinds.length ? kinds : ["manual"] };
}

function notAnAutomation(W) {
  const live = W.order.map((n) => W.infos.get(n)).filter((d) => !d.disabled);
  const training = live.filter((d) => TRAINING_TYPES.has(d.baseType));
  if (training.length) return { reason: "uses n8n's tutorial data nodes", nodes: training.map((d) => d.name) };
  if (!W.wakeup.all.every((k) => k === "manual")) return null;
  const functional = live.filter((d) => d.role !== "annotation");
  if (functional.some((d) => d.status !== "mapped")) return null;
  const io = functional.some((d) => ["connector", "http", "db", "media", "vector", "subworkflow", "blocked"].includes(d.kind) || d.connector || d.secrets === true);
  if (io) return null;
  if (functional.some((d) => (d.role === "step" || d.role === "subnode") && d.effect !== "none" && d.effect !== "read")) return null;
  const notes = W.order.map((n) => W.infos.get(n)).filter((d) => d.role === "annotation");
  const chars = notes.reduce((a, d) => a + txt(d.params.content).replace(/\s+/g, " ").trim().length, 0);
  if (chars >= TUTORIAL_NOTE_MIN_CHARS && chars >= TUTORIAL_NOTE_CHARS_PER_NODE * Math.max(1, functional.length))
    return { reason: `manual trigger only, no outside effect, ${chars} characters of sticky notes for ${functional.length} nodes`, nodes: [] };
  return null;
}

// Nothing to migrate: a workflow whose only effects are on n8n's own storage
// or on n8n itself. Kept narrow on purpose, since the flag tells the person
// there is nothing to schedule:
// - storage setup: run by hand (a manual trigger, plus at most plain Webhook
//   triggers that start the same steps), at least one Data Table create, and
//   otherwise only seed-row inserts, Data Table reads and steps with no
//   effect. After a move the target's state store replaces the tables.
// - n8n management: every step with an effect is the n8n API node.
// Anything else (an outside call, a model, a sub-workflow, an unmapped node,
// another trigger) clears the flag. The outcome itself is not changed.
const SETUP_TABLE_OPS = new Set(["table:create", "row:insert", "row:get", "row:rowExists", "row:rowNotExists", "table:list"]);
function setupOnly(W) {
  const steps = W.order.map((n) => W.infos.get(n)).filter((d) => !d.disabled && W.branch.get(d.name) === "main" && !d.isTrigger && d.role !== "annotation");
  const tables = [];
  let creates = 0;
  let manages = 0;
  for (const d of steps) {
    if (d.status !== "mapped") return null;
    if (NEUTRAL_STEP_TYPES.has(d.type) || ((d.kind === "logic" || d.kind === "code") && d.effect === "none")) continue;
    if (d.baseType === "n8n-nodes-base.dataTable" && d.role === "step" && SETUP_TABLE_OPS.has(d.opKey)) {
      if (d.opKey === "table:create") {
        creates++;
        const t = d.params.tableName;
        tables.push(typeof t === "string" && t && !isExpr(t) ? t : "a table named at run time");
      }
      continue;
    }
    if (d.baseType === "n8n-nodes-base.n8n") {
      manages++;
      continue;
    }
    return null;
  }
  if (manages && !creates && steps.every((d) => d.baseType !== "n8n-nodes-base.dataTable")) return { reason: "it only manages n8n itself through the n8n API: nothing to move once n8n is gone" };
  const byHand = W.triggers.some((t) => t.kind === "manual") && W.triggers.every((t) => t.kind === "manual" || t.d.baseType === "n8n-nodes-base.webhook");
  if (creates && !manages && byHand)
    return { reason: `it only creates n8n Data Tables (${uniq(tables).join(", ")}) and seeds them, run by hand: recreate the storage in the target, nothing to schedule` };
  return null;
}

