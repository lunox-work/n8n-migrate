// Known key shapes first, then generic ones; a later match that overlaps an
// earlier one in the same string is skipped. Group 1, when present, is the
// secret itself.
const SECRET_PATTERNS = [
  ["anthropic", /sk-ant-[A-Za-z0-9_-]{20,}/g],
  ["stripe", /\b[rs]k_(?:live|test)_[A-Za-z0-9]{16,}/g],
  ["openai", /\bsk-(?:proj-|svcacct-|admin-)?[A-Za-z0-9_-]{20,}/g],
  ["slack", /\bxox[abposr]-[A-Za-z0-9-]{10,}/g],
  ["slack-webhook", /hooks\.slack\.com\/services\/([A-Za-z0-9/_-]{20,})/g],
  ["google", /\bAIza[0-9A-Za-z_-]{35}/g],
  ["github", /\b(?:gh[pousr]_[A-Za-z0-9]{36,}|github_pat_[A-Za-z0-9_]{22,})/g],
  ["aws", /\b(?:AKIA|ASIA)[0-9A-Z]{16}\b/g],
  ["telegram", /\bbot(\d{6,12}:[A-Za-z0-9_-]{30,})/g],
  ["jwt", /\beyJ[A-Za-z0-9_-]{8,}\.eyJ[A-Za-z0-9_-]{8,}\.[A-Za-z0-9_-]{8,}/g],
  ["bearer", /\bBearer\s+([A-Za-z0-9._~+/-]{20,}=*)/g],
  ["query-param", /[?&](?:api[_-]?key|apikey|key|token|access[_-]?token|auth[_-]?token|secret)=([^&\s"'#]{16,})/gi],
  ["key-value", /["']?(?:api[_-]?key|apikey|access[_-]?token|auth[_-]?token|secret[_-]?key|client[_-]?secret|password|token)["']?\s*[:=]\s*["']([^"'\s]{16,})["']/gi],
];
const SECRET_NAME = /^(?:x-)?(?:api[-_]?key|apikey|access[-_]?token|auth|authorization|token|secret|client[-_]?secret|password|key)$/i;

function isPlaceholder(v) {
  return (
    /^(?:your|my|insert|enter|replace|put|add|paste)[\s_-]?/i.test(v) ||
    /x{4,}|X{4,}|\*{3,}|\.{3}|[<>{}[\]]/.test(v) ||
    /here|example|placeholder|dummy|changeme|redacted/i.test(v) ||
    /(.)\1{7,}/.test(v)
  );
}

export function redact(v) {
  return `${String(v).slice(0, 4)}…${String(v).length}`;
}

// Finds secret-looking literals in one string. In an expression string
// (starting with "=") only the literal text outside {{ }} is scanned.
export function findSecrets(s) {
  const text = s.startsWith("=") ? s.slice(1).replace(/\{\{[\s\S]*?\}\}/g, (m) => " ".repeat(m.length)) : s;
  const spans = [];
  const out = [];
  for (const [kind, re] of SECRET_PATTERNS) {
    re.lastIndex = 0;
    for (let m; (m = re.exec(text)); ) {
      const value = m[1] ?? m[0];
      const start = m.index + (m[1] !== undefined ? m[0].indexOf(m[1]) : 0);
      const end = start + value.length;
      if (spans.some(([a, b]) => start < b && end > a)) continue;
      if (isPlaceholder(value)) continue;
      spans.push([start, end]);
      out.push({ kind, value });
    }
  }
  return out;
}

// Walks every string under `root`; also flags {name, value} pairs whose name
// says secret (HTTP Request header and query parameter lists).
export function scanSecrets(root, path) {
  const out = [];
  const walk = (v, p) => {
    if (typeof v === "string") {
      for (const f of findSecrets(v)) out.push({ path: p, kind: f.kind, redacted: redact(f.value) });
    } else if (Array.isArray(v)) v.forEach((x, i) => walk(x, `${p}[${i}]`));
    else if (isObj(v)) {
      if (typeof v.name === "string" && typeof v.value === "string" && SECRET_NAME.test(v.name.trim()) && !v.value.startsWith("=")) {
        const val = v.value.trim();
        if (val.length >= 16 && !isPlaceholder(val) && !findSecrets(v.value).length) out.push({ path: `${p}.value`, kind: "named-param", redacted: redact(val) });
      }
      for (const [k, x] of Object.entries(v)) walk(x, `${p}.${k}`);
    }
  };
  walk(root, path);
  return out;
}

// ---------- cron ----------

const MONTHS = ["jan", "feb", "mar", "apr", "may", "jun", "jul", "aug", "sep", "oct", "nov", "dec"];
const DAYS = ["sun", "mon", "tue", "wed", "thu", "fri", "sat"];
const CRON_FIELDS = [
  { name: "second", min: 0, max: 59 },
  { name: "minute", min: 0, max: 59 },
  { name: "hour", min: 0, max: 23 },
  { name: "day of month", min: 1, max: 31 },
  { name: "month", min: 1, max: 12, names: MONTHS, base: 1 },
  { name: "day of week", min: 0, max: 7, names: DAYS, base: 0 },
];

function cronValue(s, f) {
  if (/^\d+$/.test(s)) return Number(s);
  const i = f.names ? f.names.indexOf(s.toLowerCase()) : -1;
  if (i < 0) throw new Error(`bad ${f.name} value "${s}"`);
  return i + f.base;
}

function cronField(text, f) {
  const set = new Set();
  for (const part of text.split(",")) {
    const m = part.match(/^([^/]+)(?:\/(\d+))?$/);
    if (!m) throw new Error(`bad ${f.name} field "${text}"`);
    const step = m[2] === undefined ? 1 : Number(m[2]);
    if (step < 1) throw new Error(`bad step in ${f.name} field "${text}"`);
    let lo;
    let hi;
    if (m[1] === "*" || m[1] === "?") [lo, hi] = [f.min, f.max];
    else if (m[1].includes("-")) {
      const [a, b] = m[1].split("-");
      [lo, hi] = [cronValue(a, f), cronValue(b, f)];
    } else {
      lo = cronValue(m[1], f);
      hi = m[2] === undefined ? lo : f.max;
    }
    if (lo < f.min || hi > f.max || lo > hi) throw new Error(`${f.name} out of range in "${text}"`);
    for (let x = lo; x <= hi; x += step) set.add(x);
  }
  return set;
}

// Parses a 5-field (minute first) or 6-field (second first) cron expression,
// the two forms n8n accepts. Months are 1-12, days of week 0-7 (0 and 7 are
// Sunday), names allowed. When both day fields are restricted a day matching
// either one fires (Vixie cron). L, W and # are not supported and throw.
export function parseCron(expr) {
  if (typeof expr !== "string") throw new Error("cron expression is not a string");
  const parts = expr.trim().split(/\s+/);
  if (parts.length === 5) parts.unshift("0");
  if (parts.length !== 6) throw new Error(`cron needs 5 or 6 fields, got ${parts.length}`);
  const sets = parts.map((p, i) => cronField(p, CRON_FIELDS[i]));
  if (sets[5].has(7)) {
    sets[5].delete(7);
    sets[5].add(0);
  }
  const sorted = (s) => [...s].sort((a, b) => a - b);
  return {
    seconds: sorted(sets[0]),
    minutes: sorted(sets[1]),
    hours: sorted(sets[2]),
    doms: sets[3],
    months: sets[4],
    dows: sets[5],
    domStar: parts[3].startsWith("*") || parts[3] === "?",
    dowStar: parts[5].startsWith("*") || parts[5] === "?",
  };
}

function cronDayMatches(c, dom, month, dow) {
  if (!c.months.has(month)) return false;
  if (c.domStar && c.dowStar) return true;
  if (c.domStar) return c.dows.has(dow);
  if (c.dowStar) return c.doms.has(dom);
  return c.doms.has(dom) || c.dows.has(dow);
}

// Simulates the expressions together, in UTC, from the start of the day of
// `nowMs`: 7 days, or 366 days when that gives fewer than 168 fires (sparse
// schedules need the longer window to be counted fairly). Returns runs per day
// and the shortest gap between two fires (null with fewer than two fires).
// Timezone and DST are ignored: they move fires, not their count.
export function simulateCron(exprs, nowMs) {
  const parsed = exprs.map(parseCron);
  const now = new Date(nowMs);
  const start = Date.UTC(now.getUTCFullYear(), now.getUTCMonth(), now.getUTCDate());
  const run = (days) => {
    let count = 0;
    let last = null;
    let minGap = null;
    for (let di = 0; di < days; di++) {
      const day = new Date(start + di * 86400000);
      const [dom, month, dow] = [day.getUTCDate(), day.getUTCMonth() + 1, day.getUTCDay()];
      let times = [];
      for (const c of parsed) {
        if (!cronDayMatches(c, dom, month, dow)) continue;
        for (const h of c.hours) for (const m of c.minutes) for (const s of c.seconds) times.push(h * 3600 + m * 60 + s);
      }
      if (parsed.length > 1) times = uniq(times).sort((a, b) => a - b);
      for (const t of times) {
        const ts = di * 86400 + t;
        if (last !== null && (minGap === null || ts - last < minGap)) minGap = ts - last;
        last = ts;
        count++;
      }
    }
    return { count, minGap, days };
  };
  let r = run(7);
  if (r.count < 7 * 24) r = run(366);
  return { runsPerDay: r.count / r.days, shortestSec: r.minGap, fires: r.count, days: r.days };
}

// ---------- schedule rules ----------

const hasExpr = (v) => allStrings(v).some(isExpr);

// n8n-workflow toCronExpression() for the legacy Cron node's triggerTimes and
// for poll triggers' pollTimes. n8n picks a random second (and a random minute
// for everyX hours); 0 stands in for both. Defaults are the parameter defaults
// of cronNodeOptions: mode everyDay, hour 14, minute 0, dayOfMonth 1,
// weekday 1, value 2, unit hours, cronExpression "* * * * * *".
export function legacyCron(item) {
  const i = isObj(item) ? item : {};
  const mode = i.mode ?? "everyDay";
  const hour = i.hour ?? 14;
  const minute = i.minute ?? 0;
  if (mode === "everyMinute") return "0 * * * * *";
  if (mode === "everyHour") return `0 ${minute} * * * *`;
  if (mode === "everyX") {
    const value = i.value ?? 2;
    if ((i.unit ?? "hours") === "minutes") return `0 */${value} * * * *`;
    return `0 0 */${value} * * *`;
  }
  if (mode === "everyDay") return `0 ${minute} ${hour} * * *`;
  if (mode === "everyWeek") return `0 ${minute} ${hour} * * ${i.weekday ?? "1"}`;
  if (mode === "everyMonth") return `0 ${minute} ${hour} ${i.dayOfMonth ?? 1} * *`;
  return String(i.cronExpression ?? "* * * * * *").trim();
}

// Schedule Trigger rule items, after withIntervalDefaults() and
// toCronExpression() in the n8n package (nodes/Schedule/GenericFunctions).
// seconds and cronExpression become cron strings. The other fields are exact
// rhythms because n8n's recurrenceCheck enforces the interval even where the
// cron step does not divide evenly. months use 28 days per month as the
// shortest gap and 30.44 for runs per day.
function scheduleRuleTimes(item) {
  const i = isObj(item) ? item : {};
  const field = ["seconds", "minutes", "hours", "days", "weeks", "months", "cronExpression"].includes(i.field) ? i.field : "days";
  const fixed = (sec) => ({ fixed: { runsPerDay: 86400 / sec, shortestSec: sec } });
  switch (field) {
    case "seconds":
      return { cron: `*/${i.secondsInterval ?? 30} * * * * *` };
    case "minutes":
      return fixed((i.minutesInterval ?? 5) * 60);
    case "hours":
      return fixed((i.hoursInterval ?? 1) * 3600);
    case "days":
      return fixed((i.daysInterval ?? 1) * 86400);
    case "weeks": {
      const n = i.weeksInterval ?? 1;
      let days = uniq([].concat(i.triggerAtDay ?? [0]).map(Number)).sort((a, b) => a - b);
      if (!days.length) days = [0, 1, 2, 3, 4, 5, 6];
      const gaps = days.slice(1).map((d, k) => d - days[k]);
      if (n === 1) gaps.push(days[0] + 7 - days.at(-1));
      const shortestDays = gaps.length ? Math.min(...gaps) : 7 * n;
      return { fixed: { runsPerDay: days.length / (7 * n), shortestSec: shortestDays * 86400 } };
    }
    case "months": {
      const n = i.monthsInterval ?? 1;
      return { fixed: { runsPerDay: 1 / (30.4375 * n), shortestSec: 28 * 86400 * n } };
    }
    case "cronExpression":
      return { cron: String(i.expression ?? "") };
  }
}

// Fire times of one time-based trigger: {crons, fixed, error}.
function triggerTimes(d) {
  const p = d.params;
  const out = { crons: [], fixed: [], error: null };
  try {
    if (d.type === "n8n-nodes-base.scheduleTrigger") {
      const rule = p.rule ?? { interval: [{ field: "days" }] };
      if (hasExpr(rule)) throw new Error("the schedule is set by an expression");
      for (const item of [].concat(rule.interval ?? [])) {
        const r = scheduleRuleTimes(item);
        if (r.cron !== undefined) {
          if (!r.cron.trim()) throw new Error("empty cron expression");
          parseCron(r.cron);
          out.crons.push(r.cron);
        } else out.fixed.push(r.fixed);
      }
    } else if (d.type === "n8n-nodes-base.interval") {
      if (hasExpr([p.interval, p.unit])) throw new Error("the interval is set by an expression");
      const n = Number(p.interval ?? 1);
      const unit = { seconds: 1, minutes: 60, hours: 3600 }[p.unit ?? "seconds"];
      if (!(n > 0) || !unit) throw new Error("invalid interval");
      out.fixed.push({ runsPerDay: 86400 / (n * unit), shortestSec: n * unit });
    } else {
      // Legacy Cron node: triggerTimes. Poll triggers: pollTimes, default
      // every minute (also used for an IMAP trigger's Gmail substitute).
      const coll = d.type === "n8n-nodes-base.cron" ? p.triggerTimes ?? {} : p.pollTimes ?? { item: [{ mode: "everyMinute" }] };
      if (hasExpr(coll)) throw new Error("the schedule is set by an expression");
      for (const item of [].concat(coll.item ?? [])) {
        const c = legacyCron(item);
        parseCron(c);
        out.crons.push(c);
      }
    }
  } catch (e) {
    out.error = e.message;
  }
  return out;
}

// ---------- graph ----------

// Number of regular main outputs; with onError continueErrorOutput the error
// output comes right after them. Multi-output nodes are listed; every other
// node has one.
function regularOutputs(d) {
  const p = d.params;
  switch (d.baseType) {
    case "n8n-nodes-base.if":
      return 2;
    case "n8n-nodes-base.compareDatasets":
      return 4;
    case "n8n-nodes-base.splitInBatches":
      return d.typeVersion >= 3 ? 2 : 1;
    case "n8n-nodes-base.switch":
      if (d.typeVersion < 3) return 4;
      if (p.mode === "expression") return Number(p.numberOutputs ?? 4) || 4;
      return ((p.rules?.values ?? []).length || 1) + (p.options?.fallbackOutput === "extra" ? 1 : 0);
    case "@n8n/n8n-nodes-langchain.textClassifier":
      return ((p.categories?.categories ?? []).length || 1) + (p.options?.fallback === "other" ? 1 : 0);
    default:
      return 1;
  }
}

function buildGraph(wf, infos) {
  const mainOut = new Map(); // name -> [[target names] per output]
  const attach = new Map(); // sub-node name -> [root names]
  const incoming = new Set();
  const conns = isObj(wf.connections) ? wf.connections : {};
  for (const [src, types] of Object.entries(conns)) {
    if (!infos.has(src) || !isObj(types)) continue;
    for (const [ctype, outputs] of Object.entries(types)) {
      if (!Array.isArray(outputs)) continue;
      outputs.forEach((list, i) => {
        for (const c of Array.isArray(list) ? list : []) {
          const dst = c?.node;
          if (!infos.has(dst)) continue;
          if (ctype === "main") {
            if (!mainOut.has(src)) mainOut.set(src, []);
            const o = mainOut.get(src);
            while (o.length <= i) o.push([]);
            o[i].push(dst);
            incoming.add(dst);
          } else {
            if (!attach.has(src)) attach.set(src, []);
            attach.get(src).push(dst);
          }
        }
      });
    }
  }
  return { mainOut, attach, incoming };
}

function errorOutputIndex(d) {
  return d.node.onError === "continueErrorOutput" ? regularOutputs(d) : -1;
}

// Breadth-first over main connections. skipError leaves out error outputs.
function reach(starts, graph, infos, skipError) {
  const seen = new Set(starts);
  const queue = [...starts];
  while (queue.length) {
    const n = queue.shift();
    const outs = graph.mainOut.get(n) || [];
    const errIdx = skipError ? errorOutputIndex(infos.get(n)) : -1;
    outs.forEach((list, i) => {
      if (i === errIdx) return;
      for (const t of list) if (!seen.has(t)) seen.add(t), queue.push(t);
    });
  }
  return seen;
}

// Adds sub-nodes (ai_* connections, transitively) attached to nodes in `set`.
function withSubnodes(set, graph) {
  const out = new Set(set);
  for (let changed = true; changed; ) {
    changed = false;
    for (const [sub, roots] of graph.attach) if (!out.has(sub) && roots.some((r) => out.has(r))) out.add(sub), (changed = true);
  }
  return out;
}

// Branch of every node: main (runs when an enabled trigger fires), error-output
// (only behind an onError continueErrorOutput output), error-trigger (only
// behind an Error Trigger), unreached. Disabled nodes pass data through, as in
// n8n, but disabled triggers do not fire. With no enabled trigger the entry
// points are the nodes without input (n8n's manual run). Unmapped nodes
// without input are entry points too: they may be triggers we cannot read.
function computeBranches(W) {
  const { infos, order, graph } = W;
  const usable = order.filter((n) => !infos.get(n).disabled && infos.get(n).role !== "annotation");
  const entries = [];
  const errorEntries = [];
  for (const n of usable) {
    const d = infos.get(n);
    if (d.isTrigger) (d.wakeup === "error" ? errorEntries : entries).push(n);
  }
  const isRoot = (n) => !graph.incoming.has(n) && !graph.attach.has(n);
  if (!entries.length && !errorEntries.length) {
    for (const n of usable) if (isRoot(n) && infos.get(n).role !== "subnode") entries.push(n);
  } else {
    for (const n of usable) if (infos.get(n).status !== "mapped" && isRoot(n) && !entries.includes(n)) entries.push(n);
  }
  const main = withSubnodes(reach(entries, graph, infos, true), graph);
  const errStarts = [];
  for (const n of main) {
    const d = infos.get(n);
    const idx = errorOutputIndex(d);
    if (idx >= 0) for (const t of (graph.mainOut.get(n) || [])[idx] || []) if (!main.has(t)) errStarts.push(t);
  }
  const errOut = withSubnodes(reach(errStarts, graph, infos, false), graph);
  const errTrig = withSubnodes(reach(errorEntries, graph, infos, false), graph);
  const branch = new Map();
  for (const n of order) branch.set(n, main.has(n) ? "main" : errOut.has(n) ? "error-output" : errTrig.has(n) ? "error-trigger" : "unreached");
  W.branch = branch;
  W.entries = entries;
}

